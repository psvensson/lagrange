import {THERMAL_ENDPOINT_ENV, THERMAL_DEADLINE_ENV, TEST_EXECUTION_CONTEXT_ENV}
  from '../checks/wait-for-thermal-headroom.js';
import {CHECK_BASE_ENV, WORKSPACE_INJECTION_ENV} from '../checks/change-selection-constants.js';
import {PROOF_CHECKOUT_GENERATORS} from '../checks/proof-checkout-preparation.js';
import {LANE_JOBS_CAP_ENV} from '../checks/test-resource-classification-constants.js';

const FILES_MARK = 'LAGRANGE_PLACEMENT_FILES';
const INJECTION_SEPARATOR = ',';
const NEWLINE = '\n';
const SHELL_WORD_SEPARATOR = ' ';
const STOP_STAGE_MS = 2000;
const SCOPE_POLL_MS = 20;
const [IMPORT_GRAPH] = PROOF_CHECKOUT_GENERATORS.map((generator) =>
  Object.freeze({name: generator.name, producer: generator.producer,
    args: generator.args.join(SHELL_WORD_SEPARATOR)}));

// This observes the declared scope only. ESRCH means absent; permission or
// any other probe error is uncertainty. Group signalling by itself cannot
// prove closure, and the direct child must have ended as well as its group.
function scopeWaitProgram(setupExit) {
  const program = [
    'const [kind, rawPid, rawBound] = process.argv.slice(1);',
    'const pid = Number(rawPid), bound = Number(rawBound);',
    'if (!Number.isInteger(pid) || pid <= 1 || !Number.isFinite(bound) || bound < 0 ||',
    `!(kind === "group" || kind === "process")) process.exit(${setupExit});`,
    'const targets = kind === "group" ? [-pid, pid] : [pid];',
    'const deadline = performance.now() + bound;',
    'function present(target) {',
    '  try { process.kill(target, 0); return true; }',
    '  catch (error) { if (error.code === "ESRCH") return false; throw error; }',
    '}',
    'function observe() {',
    '  try {',
    '    const alive = targets.map(present).some(Boolean);',
    '    if (!alive) process.exit(0);',
    '    if (performance.now() >= deadline) process.exit(1);',
    `    setTimeout(observe, ${SCOPE_POLL_MS});`,
    '  } catch (error) {',
    '    console.error(`placement: cleanup unavailable: ${kind} ${pid}: ${error.message}`);',
    `    process.exit(${setupExit});`,
    '  }',
    '}',
    'observe();',
  ];
  return program.join(SHELL_WORD_SEPARATOR);
}

// One generated ssh execution body, reached through placementScript(files).
// Lock definitions and execution policy are supplied by the placement owner;
// there is no alternate shell or runner when a required capability is absent.
export function placementShell(files, {exit, locks, parent, resultsPrefix,
  machineFactorEnv, placementEnv, localMode, tapTimeoutEnv}) {
  const scopeWait = scopeWaitProgram(exit.SETUP);
  const lines = [
    'set -u',
    'repo="$1"; sha="$2"; node_major="$3"; factor="$4"; run="$5"; bundle="$6"',
    'tap_timeout="$7"; check_base="$8"; results="$9"; lock_wait="${10}"',
    'holder_head="${11}"; expected_minutes="${12}"',
    'thermal_endpoint="${13}"; thermal_budget="${14}"; lane_cap="${15}"',
    'thermal_started="$(date +%s)"',
    'set --',
    'first_status=0; waiter_pid=""; group_pid=""; holding=""',
    'scope_stop_started=""; scope_stop_status=0; scope_uncertain=""',
    'wt_owned=""; wt_attempted=""; list_owned=""; ref_owned=""',
    ...locks.paths,
    `parent="$repo/${parent}"`,
    'wt="$parent/$run"; list="$parent/$run.files"; ref="refs/lagrange-placement/$run"',
    'record_status() { if [ "$first_status" = 0 ] && [ "$1" != 0 ]; then first_status="$1"; fi; }',
    'scope_closed() {',
    `  node -e '${scopeWait}' "$scope_kind" "$scope_pid" "$1"`,
    '}',
    // A single TERM stage and a single forced-closure stage fit inside the
    // controller's existing five-second abort grace, leaving finalization time.
    'stop_scope() {',
    '  if [ -n "$scope_stop_started" ]; then return "$scope_stop_status"; fi',
    '  if [ -n "$group_pid" ]; then scope_kind=group; scope_pid="$group_pid"',
    '  elif [ -n "$waiter_pid" ]; then scope_kind=process; scope_pid="$waiter_pid"',
    '  else return 0; fi',
    '  scope_stop_started=1',
    '  case "$scope_pid" in ""|0|1|*[!0-9]*)',
    '    echo "placement: cleanup unavailable: unacquired scope identity $scope_pid" >&2',
    `    scope_uncertain=1; scope_stop_status=${exit.SETUP}; return "$scope_stop_status";; esac`,
    '  if [ "$scope_kind" = group ]; then',
    '    kill -s TERM -- "-$group_pid" 2>/dev/null',
    '  else kill -s TERM -- "$waiter_pid" 2>/dev/null; fi',
    `  scope_closed ${STOP_STAGE_MS}; stopped=$?`,
    '  if [ "$stopped" = 1 ]; then',
    '    if [ "$scope_kind" = group ]; then',
    '      kill -s KILL -- "-$group_pid" 2>/dev/null',
    '    else kill -s KILL -- "$waiter_pid" 2>/dev/null; fi',
    `    scope_closed ${STOP_STAGE_MS}; stopped=$?`,
    '  fi',
    '  if [ "$stopped" != 0 ]; then',
    '    echo "placement: cleanup unavailable: $scope_kind $scope_pid closure unconfirmed" >&2',
    `    scope_uncertain=1; scope_stop_status=${exit.SETUP}`,
    '    return "$scope_stop_status"',
    '  fi',
    '  wait "$scope_pid" 2>/dev/null',
    '  group_pid=""; waiter_pid=""',
    '  return 0',
    '}',
    'cleanup_unavailable() {',
    '  echo "placement: cleanup unavailable: $1" >&2',
    `  record_status ${exit.SETUP}`,
    '}',
    'cleanup() {',
    '  record_status "$?"',
    // Execution is already terminal before synchronous custody finalization.
    // Repeated signals cannot restart a stop bound or a removal attempt.
    '  trap - EXIT; trap "" HUP INT TERM',
    '  if [ -n "$group_pid$waiter_pid" ]; then',
    `    record_status ${exit.SETUP}`,
    '    stop_scope || cleanup_unavailable "owned execution scope remains uncertain"',
    '  fi',
    '  if [ "$first_status" != 0 ] || [ -n "$scope_uncertain" ]; then',
    '    if [ -n "$wt_owned" ]; then echo "placement: retained original checkout $wt" >&2',
    '    elif [ -n "$wt_attempted" ]; then',
    '      echo "placement: retained uncertain checkout acquisition $wt" >&2',
    '    fi',
    '  elif [ -n "$wt_owned" ]; then',
    '    if git -C "$repo" worktree remove --force "$wt"; then',
    '      wt_owned=""',
    '      if [ -n "$ref_owned" ]; then',
    '        git -C "$repo" update-ref -d "$ref" "$sha" || cleanup_unavailable "$ref"',
    '      fi',
    '      if [ "$first_status" = 0 ]; then',
    '        if [ -n "$list_owned" ]; then rm -f "$list" || cleanup_unavailable "$list"; fi',
    '        if [ -n "$bundle" ]; then rm -f "$bundle" || cleanup_unavailable "$bundle"; fi',
    '      fi',
    '    else cleanup_unavailable "$wt"; fi',
    '  fi',
    '  if [ -n "$holding" ]; then rm -f "$lab_holder" || cleanup_unavailable "$lab_holder"; fi',
    '  exit "$first_status"',
    '}',
    'stop() {',
    '  trap "" HUP INT TERM',
    `  record_status ${exit.TERMINATED}`,
    '  stop_scope || cleanup_unavailable "interrupted execution scope remains uncertain"',
    '  exit "$first_status"',
    '}',
    'trap cleanup EXIT',
    'trap stop HUP INT TERM',
    'echo "placement-shell=$$"',
    `cd "$repo" || exit ${exit.SETUP}`,
    'if ! command -v flock >/dev/null 2>&1 || ! command -v setsid >/dev/null 2>&1; then',
    '  echo "placement needs flock and setsid on this machine" >&2',
    `  exit ${exit.SETUP}`,
    'fi',
    'NVM_DIR="${NVM_DIR:-$HOME/.nvm}"',
    '[ -s "$NVM_DIR/nvm.sh" ] && . "$NVM_DIR/nvm.sh" >/dev/null 2>&1 && ' +
      '[ -n "$node_major" ] && nvm use "$node_major" >/dev/null 2>&1',
    'command -v node >/dev/null 2>&1 || { echo "placement needs node on this machine" >&2; ' +
      `exit ${exit.SETUP}; }`,
    `common="$(git rev-parse --git-common-dir)" || exit ${exit.SETUP}`,
    'case "$common" in /*) ;; *) common="$repo/$common";; esac',
    ...locks.take,
    'exec 8>"$common/lagrange-placement.lock"',
    `flock -n 8 || { echo "${locks.busyLine}"; exit ${exit.BUSY}; }`,
    ...locks.record,
    `mkdir -p "$parent" || exit ${exit.SETUP}`,
    // The machine lock serializes admission, while exclusive file/ref writes
    // reject a colliding claimant. Earlier attempts are never swept or pruned.
    'for original in "$wt" "$list"; do',
    '  if [ -e "$original" ] || [ -L "$original" ]; then',
    '    echo "placement: unavailable - attempt already exists: $original" >&2',
    `    exit ${exit.SETUP}`,
    '  fi',
    'done',
    'if [ -z "$bundle" ] && { [ -e "$wt.bundle" ] || [ -L "$wt.bundle" ]; }; then',
    '  echo "placement: unavailable - attempt already exists: $wt.bundle" >&2',
    `  exit ${exit.SETUP}`,
    'fi',
    'git show-ref --verify --quiet "$ref"; ref_status=$?',
    'if [ "$ref_status" = 0 ]; then',
    '  echo "placement: unavailable - attempt already exists: $ref" >&2',
    `  exit ${exit.SETUP}`,
    `elif [ "$ref_status" != 1 ]; then exit ${exit.SETUP}; fi`,
    'if ! (set -C; : > "$list"); then',
    '  echo "placement: unavailable - attempt already exists: $list" >&2',
    `  exit ${exit.SETUP}`,
    'fi',
    'list_owned=1',
    'if [ -n "$bundle" ]; then',
    '  bundle_ref=$(git bundle list-heads "$bundle" | awk \'NR==1 {print $2}\')',
    `  [ -n "$bundle_ref" ] || exit ${exit.SETUP}`,
    `  git fetch --quiet "$bundle" "$bundle_ref" || exit ${exit.SETUP}`,
    'fi',
    `git update-ref "$ref" "$sha" "" || exit ${exit.SETUP}`,
    'ref_owned=1; wt_attempted=1',
    `git worktree add --detach --quiet "$wt" "$sha" || exit ${exit.SETUP}`,
    'wt_owned=1',
    `[ "$(git -C "$wt" rev-parse HEAD)" = "$sha" ] || exit ${exit.SETUP}`,
    'echo "placement-head=$(git -C "$wt" rev-parse HEAD)"',
    // Use the existing workspace-injection contract. Only ignored content
    // from the source workspace is linked; every created link is declared.
    'injected=""',
    'for dir in node_modules data tools; do',
    '  [ -e "$repo/$dir" ] || continue',
    '  if [ ! -e "$wt/$dir" ] && git -C "$repo" check-ignore -q "$dir"; then',
    `    ln -s "$repo/$dir" "$wt/$dir" || exit ${exit.SETUP}`,
    '    echo "placement-link=$dir"',
    `    injected="\${injected:+$injected${INJECTION_SEPARATOR}}$dir"`,
    '    continue',
    '  fi',
    `  mkdir -p "$wt/$dir" || exit ${exit.SETUP}`,
    '  for entry in "$repo/$dir"/* "$repo/$dir"/.[!.]*; do',
    '    [ -e "$entry" ] || continue',
    '    name="$dir/${entry##*/}"',
    '    [ -e "$wt/$name" ] && continue',
    '    git -C "$repo" check-ignore -q "$name" || continue',
    `    ln -s "$entry" "$wt/$name" || exit ${exit.SETUP}`,
    '    echo "placement-link=$name"',
    `    injected="\${injected:+$injected${INJECTION_SEPARATOR}}$name"`,
    '  done',
    'done',
    `cat > "$list" <<'${FILES_MARK}' || exit ${exit.SETUP}`,
    ...files,
    FILES_MARK,
    `cd "$wt" || exit ${exit.SETUP}`,
    'run_phase() {',
    '  phase="$1"; phase_input="$2"; shift 2',
    '  scope_stop_started=""; scope_stop_status=0',
    // File-backed stdin remains complete for the synchronous classified reader.
    '  setsid "$@" < "$phase_input" 8>&- 9>&- & group_pid=$!',
    '  if [ "$phase" = runner ]; then echo "placement-pid=$group_pid"; fi',
    '  wait "$group_pid"; phase_status=$?',
    '  if [ "$phase_status" != 0 ]; then',
    `    if [ "$phase" = preparation ]; then record_status ${exit.SETUP}`,
    '    else record_status "$phase_status"; fi',
    '  fi',
    '  scope_kind=group; scope_pid="$group_pid"',
    '  scope_closed 0; closed_status=$?',
    '  if [ "$closed_status" = 0 ]; then group_pid=""',
    '  else',
    '    cleanup_unavailable "process group $group_pid remains after direct child exit"',
    '    stop_scope || cleanup_unavailable "execution scope remains uncertain"',
    '  fi',
    '  return "$first_status"',
    '}',
    `[ -f ${IMPORT_GRAPH.producer} ] || { ` +
      `echo "placement: required ${IMPORT_GRAPH.name} producer unavailable: ` +
      `${IMPORT_GRAPH.producer}" >&2; exit ${exit.SETUP}; }`,
    `if ! run_phase preparation /dev/null node ${IMPORT_GRAPH.producer} ${IMPORT_GRAPH.args} ` +
      '>/dev/null; then',
    '  echo "placement: the import graph could not be generated (exit $phase_status)" >&2',
    '  exit "$first_status"',
    'fi',
    'stale="$(git status --porcelain --untracked-files=no)"; stale_status=$?',
    `[ "$stale_status" = 0 ] || exit ${exit.SETUP}`,
    'if [ -n "$stale" ]; then',
    '  echo "placement: the commit\'s generated metadata is stale; regenerate and commit $stale" >&2',
    `  exit ${exit.SETUP}`,
    'fi',
    `echo "placement-prepared=${IMPORT_GRAPH.name}"`,
    `export ${machineFactorEnv}="$factor" ${placementEnv}=${localMode} ` +
      `${WORKSPACE_INJECTION_ENV}="$injected"`,
    `if [ -n "$tap_timeout" ]; then export ${tapTimeoutEnv}="$tap_timeout"; fi`,
    `if [ -n "$check_base" ]; then export ${CHECK_BASE_ENV}="$check_base"; ` +
      `else unset ${CHECK_BASE_ENV}; fi`,
    `unset ${TEST_EXECUTION_CONTEXT_ENV}`,
    `export ${THERMAL_ENDPOINT_ENV}="$thermal_endpoint"`,
    'case "$thermal_budget" in ""|0|*[!0-9]*) exit ' + String(exit.SETUP) + ';; esac',
    `export ${THERMAL_DEADLINE_ENV}=$((thermal_started * 1000 + thermal_budget))`,
    'if [ -n "$lane_cap" ]; then',
    '  case "$lane_cap" in 0|*[!0-9]*) exit ' + String(exit.SETUP) + ';; esac',
    `  export ${LANE_JOBS_CAP_ENV}="$lane_cap"`,
    `else unset ${LANE_JOBS_CAP_ENV}; fi`,
    `echo "placement-env=factor:$${machineFactorEnv} mode:$${placementEnv} ` +
      `timeout:\${${tapTimeoutEnv}:-} lanecap:\${${LANE_JOBS_CAP_ENV}:-} ` +
      `base:\${${CHECK_BASE_ENV}:-}"`,
    'run_phase runner "$list" node scripts/run-classified-test-files.js --stdin',
    // The ledger relay is the existing representation. Original TAP/output
    // remains in every failed or uncertain checkout; no report importer is added.
    'if [ -n "$results" ] && [ -f "$wt/$results" ]; then',
    `  sed 's/^/${resultsPrefix}/' "$wt/$results" || record_status ${exit.SETUP}`,
    'fi',
    'exit "$first_status"',
  ];
  return lines.join(NEWLINE) + NEWLINE;
}
