#!/usr/bin/env node

// Generates .kiro/steering/llm/tools-index.md: a COMPLETE, always-current index
// of every package.json script, grouped by prefix. Descriptions are sourced from
// the curated quickstart (list-commands.js COMMAND_GROUPS) first, then the
// long-tail sidecar (.kiro/steering/tool-descriptions.json); scripts with neither
// fall back to their raw command so an entry is never wrong, only less rich.
//
// Run via `npm run steering:llm:pack`; `steering:check` then fails if the
// committed index drifts from package.json (a new undocumented script is the
// drift this catches).

import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';
import {COMMAND_GROUPS} from './list-commands.js';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(SCRIPT_DIR, '..');
const PACKAGE_JSON_PATH = join(REPO_ROOT, 'package.json');
const SIDECAR_PATH = join(REPO_ROOT, '.kiro/steering/tool-descriptions.json');
const OUTPUT_PATH = join(REPO_ROOT, '.kiro/steering/llm/tools-index.md');

const NEWLINE = '\n';
const EMPTY_TEXT = '';
const PREFIX_SEPARATOR = ':';
const TOP_LEVEL_GROUP = 'top-level';
const QUICKSTART_COMMAND = 'npm run commands';
const HARNESS_README = 'test/distributed/harness/README.md';
const COMMAND_PATTERN = /^npm (?:--silent )?run (\S+)/u;

function curatedDescriptions() {
  const map = new Map();
  for (const group of COMMAND_GROUPS) {
    for (const entry of group.commands) {
      const match = COMMAND_PATTERN.exec(entry.command);
      if (match && !map.has(match[1])) {
        map.set(match[1], entry.description);
      }
    }
  }
  return map;
}

function sidecarDescriptions() {
  try {
    const raw = readFileSync(SIDECAR_PATH, 'utf8');
    return new Map(Object.entries(JSON.parse(raw)));
  } catch {
    return new Map();
  }
}

function prefixOf(name) {
  const index = name.indexOf(PREFIX_SEPARATOR);
  return index === -1 ? TOP_LEVEL_GROUP : name.slice(0, index);
}

function groupScripts(scripts) {
  const groups = new Map();
  for (const name of Object.keys(scripts).sort()) {
    const prefix = prefixOf(name);
    if (!groups.has(prefix)) {
      groups.set(prefix, []);
    }
    groups.get(prefix).push(name);
  }
  return groups;
}

function describe(name, command, curated, sidecar) {
  const description = curated.get(name) ?? sidecar.get(name);
  if (description) {
    return {text: description, described: true};
  }
  return {text: `\`${command}\``, described: false};
}

function orderedGroupNames(groups) {
  const names = [...groups.keys()].sort();
  return names.includes(TOP_LEVEL_GROUP) ?
    [TOP_LEVEL_GROUP, ...names.filter((name) => name !== TOP_LEVEL_GROUP)] :
    names;
}

function render(scripts, curated, sidecar) {
  const groups = groupScripts(scripts);
  let described = 0;
  let total = 0;
  const lines = [
    '<!-- GENERATED by scripts/gen-tools-index.js via `npm run steering:llm:pack`. Do not hand-edit. -->',
    '<!-- Add or improve descriptions in scripts/list-commands.js (curated quickstart) or .kiro/steering/tool-descriptions.json (long tail). -->',
    EMPTY_TEXT,
    '# Tooling Index',
    EMPTY_TEXT,
    'Complete index of every `package.json` script. Before writing an ad-hoc',
    'shell command for a repo task (log triage, cleanup, extraction, validation),',
    'prefer a script listed here. The curated quickstart is `' + QUICKSTART_COMMAND + '`;',
    'for distributed or harness work, read [`' + HARNESS_README + '`](../../../' + HARNESS_README + ') first.',
    EMPTY_TEXT,
    'Invoke any entry with `npm run <name>` (pass flags after `--`).',
    EMPTY_TEXT,
  ];
  for (const prefix of orderedGroupNames(groups)) {
    lines.push(`## ${prefix}`, EMPTY_TEXT);
    for (const name of groups.get(prefix)) {
      total += 1;
      const {text, described: hit} = describe(
        name,
        scripts[name],
        curated,
        sidecar,
      );
      if (hit) {
        described += 1;
      }
      lines.push(`- \`${name}\` — ${text}`);
    }
    lines.push(EMPTY_TEXT);
  }
  lines.push(
    '---',
    EMPTY_TEXT,
    `${total} scripts indexed; ${described} have a curated description, ` +
      `${total - described} fall back to their raw command. ` +
      'Improve coverage in the two sources named in the header comment.',
    EMPTY_TEXT,
  );
  return lines.join(NEWLINE);
}

function main() {
  const scripts = JSON.parse(readFileSync(PACKAGE_JSON_PATH, 'utf8')).scripts;
  const output = render(scripts, curatedDescriptions(), sidecarDescriptions());
  writeFileSync(OUTPUT_PATH, output);
  process.stdout.write(`Wrote ${OUTPUT_PATH}${NEWLINE}`);
}

main();
