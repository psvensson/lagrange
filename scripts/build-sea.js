/**
 * Build a bundle for SEA packaging.
 * @param {string} entryPoint - Entry point file path
 * @param {string} outputFile - Output bundle basename
 * @param {string} name - Bundle name for logging
 * @param {string[]} external - External packages
 * @param {string} [format] - esbuild output format
 */
async function buildBundle(entryPoint, outputFile, name, external, format) {
  console.log(`Building ${name} bundle...`);

  const startTime = Date.now();
  const outputFormat = format || LOCAL_STR_CJS;

  await esbuild.build({
    entryPoints: [entryPoint],
    bundle: true,
    platform: LOCAL_STR_NODE,
    target: LOCAL_STR_NODE22,
    outfile: join(projectRoot, LOCAL_STR_DIST, outputFile),
    format: outputFormat,
    external,
    minify: true,
    sourcemap: false,
    treeShaking: true,
    plugins: [
      {
        name: INLINE_PIPELINE_ROUTER_IMPORTS_PLUGIN,
        setup(buildPlugin) {
          buildPlugin.onLoad({filter: /service-pipeline-router\.js$/}, (args) => {
            const source = readFileSync(args.path, 'utf8');
            const contents = source
              .replace(
                'import(LOCAL_OCI_LAYOUT_BUILDER_SPECIFIER)',
                'import(\'../service/service-local-oci-layout-builder.js\')',
              )
              .replace(
                'import(SQL_CLIENT_SPECIFIER)',
                'import(\'./service-lifecycle-sql-client.js\')',
              );
            return {contents, loader: JS_LOADER};
          });
        },
      },
    ],
    define: {
      'process.env.SEA_BUILD': LOCAL_STR_TRUE,
    },
    banner: outputFormat === LOCAL_STR_CJS ?
      {js: BUILD_BANNER} :
      undefined,
  });

  const duration = Date.now() - startTime;
  console.log(`  ✓ ${name} bundle created in ${duration}ms`);
}

/**
 * Stage filesystem-backed runtime packages beside the bundled output.
 */
function stageRuntimePackages() {
  const runtimeNodeModulesDir = join(projectRoot, 'dist', 'node_modules');
  rmSync(runtimeNodeModulesDir, {recursive: true, force: true});
  mkdirSync(runtimeNodeModulesDir, {recursive: true});

  for (const packageName of RUNTIME_PACKAGES) {
    const sourceDir = join(projectRoot, 'node_modules', packageName);
    const targetDir = join(runtimeNodeModulesDir, packageName);
    cpSync(sourceDir, targetDir, {recursive: true});
    console.log(`  ✓ staged runtime package ${packageName}`);
  }

  // The WASM-first `service init` scaffold vendors the guest-safe
  // authoring library from a directory beside the executable in SEA
  // builds (service-wasm-scaffold.js authoringSourceDirectory).
  const authoringTarget = join(
    projectRoot, LOCAL_STR_DIST, STAGED_AUTHORING_DIR_NAME);
  rmSync(authoringTarget, {recursive: true, force: true});
  cpSync(
    join(projectRoot, AUTHORING_SOURCE_PARENT, STAGED_AUTHORING_DIR_NAME),
    authoringTarget,
    {recursive: true});
  console.log(LOCAL_STR_STAGED_AUTHORING);

  const witTarget = join(projectRoot, LOCAL_STR_DIST, STAGED_WIT_DIR_NAME);
  rmSync(witTarget, {recursive: true, force: true});
  mkdirSync(witTarget, {recursive: true});
  const witSource = existsSync(join(projectRoot, 'src', 'runtime', 'wit', STAGED_WIT_FILE_NAME)) ?
    join(projectRoot, 'src', 'runtime', 'wit', STAGED_WIT_FILE_NAME) :
    join(projectRoot, 'wit', STAGED_WIT_WORLD_NAME);
  cpSync(witSource, join(witTarget, STAGED_WIT_FILE_NAME));
  cpSync(witSource, join(witTarget, STAGED_WIT_WORLD_NAME));
  console.log(LOCAL_STR_STAGED_WIT);

  stageRaftRsBinding();
}

/**
 * Stage the vendored raft-rs binding beside the bundle at the path it has in
 * the repository: the runtime owner resolves it through the SEA runtime-file
 * resolver (executable sibling, then bundle sibling), and both read the
 * layout from RAFT_RS_BINDING_LAYOUT rather than spelling it.
 */
function stageRaftRsBinding() {
  const bindingTarget = join(
    projectRoot, LOCAL_STR_DIST, ...RAFT_RS_BINDING_LAYOUT.ROOT);
  rmSync(bindingTarget, {recursive: true, force: true});
  for (const entry of RAFT_RS_BINDING_LAYOUT.STAGED_ENTRIES) {
    cpSync(
      join(projectRoot, ...RAFT_RS_BINDING_LAYOUT.ROOT, entry),
      join(bindingTarget, entry),
      {recursive: true});
  }
  console.log(LOCAL_STR_STAGED_RAFT_RS_BINDING);
}

const SMOKE_HELP_FLAG = '--help';
const SMOKE_DRY_RUN_FLAG = '--dry-run';
const SMOKE_DATA_DIR_FLAG = '--data-dir';
const SMOKE_TEMP_PREFIX = 'lagrange-sea-bundle-smoke-';
const SMOKE_UTF8 = 'utf8';
const SMOKE_CLI_BUNDLE = 'admin-cli.bundle.cjs';
const SMOKE_MAIN_BUNDLE = 'index.bundle.cjs';
const SMOKE_NODE_MODULES_DIR = 'node_modules';
const SMOKE_DIR_SYMLINK_TYPE = 'dir';
const SMOKE_VERIFIED_MSG = '  \u2713 smoke-tested SEA CJS bundles (--help, --dry-run)';
const MERGE_SMOKE_TEMP_PREFIX = 'lagrange-sea-merge-smoke-';
const MERGE_WORKER_FLAG = '--lagrange-coordinator-merge-worker';
const MERGE_SEA_BUILD_TRUE = 'true';
const MERGE_IPC_STDIO = ['ignore', 'pipe', 'pipe', 'ipc'];
const MERGE_EVENT_MESSAGE = 'message';
const MERGE_EVENT_ERROR = 'error';
const MERGE_EVENT_EXIT = 'exit';
const MERGE_EVENT_DATA = 'data';
const MERGE_IPC_INIT_SESSION = 'INIT_SESSION';
const MERGE_IPC_INIT_ACK = 'INIT_ACK';
const MERGE_IPC_INGEST_CHUNK = 'INGEST_CHUNK';
const MERGE_IPC_INGEST_ACK = 'INGEST_ACK';
const MERGE_IPC_EXECUTE_MERGE = 'EXECUTE_MERGE';
const MERGE_IPC_MERGE_RESULT = 'MERGE_RESULT';
const MERGE_CODEC_VERSION = 1;
const MERGE_TABLE_NAME = 'items';
const MERGE_COL_ID = 'id';
const MERGE_COL_NAME = 'name';
const MERGE_COL_TYPE_INTEGER = 'INTEGER';
const MERGE_COL_TYPE_TEXT = 'TEXT';
const MERGE_ROW_CLASSES = 'it';
const MERGE_ROW_ID_ONE = '1';
const MERGE_ROW_ID_TWO = '2';
const MERGE_ROW_NAME_ALPHA = 'alpha';
const MERGE_ROW_NAME_BETA = 'beta';
const MERGE_QUERY_SQL = 'SELECT id, name FROM items ORDER BY id';
const MERGE_EMPTY_CLASSES = '';
const MERGE_TIMEOUT_MS = 15000;
const MERGE_SIGNAL_SIGKILL = 'SIGKILL';
const MERGE_EXPECTED_ROW_COUNT = 2;
const MERGE_ROW_ID_INDEX = 1;
const MERGE_ROW_NAME_INDEX = 2;
const MERGE_EXIT_TIMEOUT_ERROR_MSG = 'Timed out waiting for isolated SEA merge worker exit';
const MERGE_VERIFIED_MSG =
  '  \u2713 smoke-tested isolated SEA merge worker (--lagrange-coordinator-merge-worker)';

function sendMergeIpcStep(child, payload, expectedType) {
  return new Promise((resolve, reject) => {
    let timer = null;
    let onMessage = null;
    let onError = null;
    let onExit = null;
    const cleanup = () => {
      if (timer !== null) {
        clearTimeout(timer);
        timer = null;
      }
      child.removeListener(MERGE_EVENT_MESSAGE, onMessage);
      child.removeListener(MERGE_EVENT_ERROR, onError);
      child.removeListener(MERGE_EVENT_EXIT, onExit);
    };
    onMessage = (message) => {
      cleanup();
      if (message?.type !== expectedType) {
        reject(new Error(
          `Expected ${expectedType} from isolated SEA merge worker, got ${JSON.stringify(message)}`,
        ));
        return;
      }
      resolve(message);
    };
    onError = (error) => {
      cleanup();
      reject(error);
    };
    onExit = (code, signal) => {
      cleanup();
      reject(new Error(
        `Isolated SEA merge worker exited before ${expectedType}: code=${code} signal=${signal}`,
      ));
    };
    timer = setTimeout(() => {
      cleanup();
      reject(new Error(`Timed out waiting for ${expectedType} from isolated SEA merge worker`));
    }, MERGE_TIMEOUT_MS);

    child.on(MERGE_EVENT_MESSAGE, onMessage);
    child.once(MERGE_EVENT_ERROR, onError);
    child.once(MERGE_EVENT_EXIT, onExit);
    child.send(payload);
  });
}

function awaitMergeWorkerCleanExit(child) {
  return new Promise((resolve, reject) => {
    if (child.exitCode !== null) {
      if (child.exitCode === 0) resolve();
      else reject(new Error(`Isolated SEA merge worker exited with code ${child.exitCode}`));
      return;
    }
    let timer = null;
    let onExit = null;
    onExit = (code, signal) => {
      if (timer !== null) {
        clearTimeout(timer);
        timer = null;
      }
      if (code === 0 && signal === null) {
        resolve();
        return;
      }
      reject(new Error(
        `Isolated SEA merge worker exited uncleanly: code=${code} signal=${signal}`,
      ));
    };
    timer = setTimeout(() => {
      child.removeListener(MERGE_EVENT_EXIT, onExit);
      reject(new Error(MERGE_EXIT_TIMEOUT_ERROR_MSG));
    }, MERGE_TIMEOUT_MS);
    child.once(MERGE_EVENT_EXIT, onExit);
    child.disconnect();
  });
}

async function verifyIsolatedMergeWorkerBundle(distDir) {
  const tempMergeDir = mkdtempSync(join(tmpdir(), MERGE_SMOKE_TEMP_PREFIX));
  const isolatedBundle = join(tempMergeDir, SMOKE_MAIN_BUNDLE);
  cpSync(join(distDir, SMOKE_MAIN_BUNDLE), isolatedBundle);
  symlinkSync(
    join(distDir, SMOKE_NODE_MODULES_DIR),
    join(tempMergeDir, SMOKE_NODE_MODULES_DIR),
    SMOKE_DIR_SYMLINK_TYPE,
  );
  const child = fork(isolatedBundle, [MERGE_WORKER_FLAG], {
    cwd: tempMergeDir,
    env: {...process.env, SEA_BUILD: MERGE_SEA_BUILD_TRUE},
    stdio: MERGE_IPC_STDIO,
  });
  let stderr = MERGE_EMPTY_CLASSES;
  child.stderr?.on(MERGE_EVENT_DATA, (chunk) => {
    stderr += String(chunk);
  });
  try {
    await sendMergeIpcStep(child, {
      type: MERGE_IPC_INIT_SESSION,
      sessionOptions: {},
      tables: [{
        tableName: MERGE_TABLE_NAME,
        schema: {
          columns: [
            {name: MERGE_COL_ID, type: MERGE_COL_TYPE_INTEGER},
            {name: MERGE_COL_NAME, type: MERGE_COL_TYPE_TEXT},
          ],
        },
        declaredColumns: [MERGE_COL_ID, MERGE_COL_NAME],
      }],
    }, MERGE_IPC_INIT_ACK);

    await sendMergeIpcStep(child, {
      type: MERGE_IPC_INGEST_CHUNK,
      tableName: MERGE_TABLE_NAME,
      columns: [MERGE_COL_ID, MERGE_COL_NAME],
      encodedRows: [
        [MERGE_ROW_CLASSES, MERGE_ROW_ID_ONE, MERGE_ROW_NAME_ALPHA],
        [MERGE_ROW_CLASSES, MERGE_ROW_ID_TWO, MERGE_ROW_NAME_BETA],
      ],
      byteLength: 0,
      executionEnvelope: null,
    }, MERGE_IPC_INGEST_ACK);

    const mergeResult = await sendMergeIpcStep(child, {
      type: MERGE_IPC_EXECUTE_MERGE,
      sql: MERGE_QUERY_SQL,
      typedParams: {v: MERGE_CODEC_VERSION, classes: MERGE_EMPTY_CLASSES, cells: []},
      expectedColumns: [MERGE_COL_ID, MERGE_COL_NAME],
      notifyExecutionStarted: false,
    }, MERGE_IPC_MERGE_RESULT);

    const rows = mergeResult.rowSet?.rows;
    const validRows = Array.isArray(rows) &&
      rows.length === MERGE_EXPECTED_ROW_COUNT &&
      rows[0]?.[MERGE_ROW_ID_INDEX] === MERGE_ROW_ID_ONE &&
      rows[0]?.[MERGE_ROW_NAME_INDEX] === MERGE_ROW_NAME_ALPHA &&
      rows[1]?.[MERGE_ROW_ID_INDEX] === MERGE_ROW_ID_TWO &&
      rows[1]?.[MERGE_ROW_NAME_INDEX] === MERGE_ROW_NAME_BETA;
    if (!validRows) {
      throw new Error(
        `Isolated SEA merge worker returned unexpected rows: ${JSON.stringify(mergeResult)}`,
      );
    }

    await awaitMergeWorkerCleanExit(child);
    console.log(MERGE_VERIFIED_MSG);
  } catch (error) {
    if (stderr.length > 0) {
      error.message = `${error.message} (stderr: ${stderr.trim()})`;
    }
    throw error;
  } finally {
    if (child.exitCode === null && !child.killed) {
      child.kill(MERGE_SIGNAL_SIGKILL);
    }
    rmSync(tempMergeDir, {recursive: true, force: true});
  }
}

async function verifySeaBundles(distDir) {
  const cliResult = spawnSync(
    process.execPath,
    [join(distDir, SMOKE_CLI_BUNDLE), SMOKE_HELP_FLAG],
    {cwd: projectRoot, encoding: SMOKE_UTF8},
  );
  if (cliResult.status !== 0) {
    throw new Error(`SEA CLI bundle smoke test failed: ${cliResult.stderr || cliResult.stdout}`);
  }
  const tempDataDir = mkdtempSync(join(tmpdir(), SMOKE_TEMP_PREFIX));
  try {
    const mainResult = spawnSync(
      process.execPath,
      [join(distDir, SMOKE_MAIN_BUNDLE), SMOKE_DRY_RUN_FLAG, SMOKE_DATA_DIR_FLAG, tempDataDir],
      {
        cwd: projectRoot,
        encoding: SMOKE_UTF8,
        env: {...process.env, NODE_HOST_ID: hostname()},
      },
    );
    if (mainResult.status !== 0) {
      throw new Error(
        `SEA Main bundle --dry-run smoke test failed: ${mainResult.stderr || mainResult.stdout}`,
      );
    }
  } finally {
    rmSync(tempDataDir, {recursive: true, force: true});
  }
  console.log(SMOKE_VERIFIED_MSG);
  await verifyIsolatedMergeWorkerBundle(distDir);
}

/**
 * Main build function.
 */
async function main() {
  console.log(LOCAL_STR_BUILDING_SEA_BUNDLES);

  const distDir = join(projectRoot, 'dist');
  if (!existsSync(distDir)) {
    mkdirSync(distDir, {recursive: true});
    console.log(LOCAL_STR_CREATED_DIST_DIRECTORY);
  }

  try {
    for (const bundle of BUNDLES) {
      await buildBundle(
        bundle.entryPoint,
        bundle.outputFile,
        bundle.name,
        bundle.external,
        bundle.format,
      );
    }

    console.log(LOCAL_STR_STAGING_RUNTIME_DEPENDENCIES);
    stageRuntimePackages();
    writeFileSync(join(distDir, RUNTIME_BUILD_MANIFEST),
      JSON.stringify(await measureRuntimeContent(projectRoot)) + LOCAL_STR_NEWLINE);
    await verifySeaBundles(distDir);

    console.log(LOCAL_STR_BUILD_COMPLETE);
    console.log(LOCAL_STR_BUNDLES_CREATED_IN_DIST);
    for (const bundle of BUNDLES) {
      console.log(`  - ${bundle.outputFile} (${bundle.name})`);
    }
    console.log(LOCAL_STR_NODE_MODULES_RUNTIME_DEPENDENCIES);
  } catch (error) {
    console.error(LOCAL_STR_BUILD_FAILED, error.message);
    process.exit(1);
  }
}

// Top-level await, not fire-and-forget: importers (the packaging smoke test
// runs this via a worker-thread dynamic import) must observe completion of
// the build when the module settles, or they race the in-flight esbuild
// writes and see partially written dist/ output.
await main();
