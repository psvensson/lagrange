#!/usr/bin/env node

/**
 * Writes an INDEX.md into every directory under src (src included): its
 * subdirectories, then one line per .js file with a one-sentence summary and
 * the number of files that import it.
 *
 *   node scripts/generate-source-owner-index.js [--write | --check] [--root <dir>]
 *
 * The summary is the first sentence of the file's leading comment (a JSDoc
 * or block comment, or contiguous line comments, before any code); with no
 * leading comment, the first JSDoc block anywhere in the file; with neither,
 * the line says so and names the first export. It is never invented. Text is
 * folded to ASCII and cut at a word boundary to 120 characters.
 *
 * Importer counts are read from the import graph the committed seal binds,
 * through loadSealedImporters, the one reader of the canonical graph that
 * scripts/generate-global-owner-debt-inventory.js produces (R05): this
 * script never builds a second graph. A graph the seal does not bind is a
 * refusal, never a guess. The index shows a band, never the exact number,
 * so an import edit elsewhere restales an index only when a file crosses a
 * band edge: none (0), one (1), few (2-5), many (6-20), hub (over 20).
 *
 * --write (the default) writes every index. --check writes nothing, prints
 * one line per missing or stale index and, as its last stdout line, their
 * count; it exits 1 when the count is above zero. That count is the
 * stale_owner_indexes budget row. A refused graph prints no count, and so
 * does an unknown argument, a repeated one or --root without a directory.
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import {fileURLToPath} from 'node:url';

import {loadSealedImporters} from './checks/helper-import-closure.js';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_ROOT = 'src';
const INDEX_FILE = 'INDEX.md';
const JAVASCRIPT_SUFFIX = '.js';
const HIDDEN_PREFIX = '.';
const UTF8 = 'utf8';
const NEWLINE = '\n';
const SPACE = ' ';
const POSIX_SEPARATOR = '/';
const EXIT_SUCCESS = 0;
const EXIT_FAILURE = 1;
const WRITE_FLAG = '--write';
const CHECK_FLAG = '--check';
const ROOT_FLAG = '--root';
const FLAG_PREFIX = '--';
const USAGE = 'usage: node scripts/generate-source-owner-index.js ' +
  '[--write | --check] [--root <dir>]';
const ARGV_OFFSET = 2;
const MODE = Object.freeze({WRITE: 'write', CHECK: 'check'});
const FINDING = Object.freeze({MISSING: 'missing', STALE: 'stale'});

// Upper bound (inclusive) of each importer band, narrowest first; a count
// above every bound is a hub.
const IMPORTER_BANDS = Object.freeze([
  Object.freeze({label: 'none', atMost: 0}),
  Object.freeze({label: 'one', atMost: 1}),
  Object.freeze({label: 'few', atMost: 5}),
  Object.freeze({label: 'many', atMost: 20}),
]);
const HUB_BAND = 'hub';

const SUMMARY_LIMIT = 120;
const ELLIPSIS = '...';
const HEADER = [
  '---',
  'documentClass: generated',
  '---',
  '<!-- GENERATED by scripts/generate-source-owner-index.js via ' +
    'npm run generate:source-owner-index. Do not hand-edit. -->',
].join(NEWLINE);
const DIRECTORIES_HEADING = '## Directories';
const FILES_HEADING = '## Files';
const NO_COMMENT_PREFIX = 'No leading comment; first export: ';
const NO_COMMENT_NO_EXPORT = 'No leading comment and no named export.';
const DEFAULT_EXPORT_NAME = 'default';
const SENTENCE_END = '.';
const REFUSAL_HINT = 'regenerate it: node scripts/generate-global-owner-debt-inventory.js ' +
  '--refresh-import-graph-only';

const SHEBANG_PATTERN = /^#![^\n]*\n/u;
const LEADING_BLOCK_PATTERN = /^\s*\/\*([\s\S]*?)\*\//u;
const LEADING_LINES_PATTERN = /^\s*((?:\/\/[^\n]*(?:\n|$))+)/u;
const JSDOC_PATTERN = /\/\*\*([\s\S]*?)\*\//u;
const BLOCK_LINE_PREFIX_PATTERN = /^\s*\*?\s?/u;
const LINE_COMMENT_PREFIX_PATTERN = /^\s*\/\/\s?/u;
const DIRECTIVE_PATTERN = /^\s*(?:eslint|global|istanbul|c8|jshint)\b/u;
const FILE_TAG_PATTERN = /^@(?:fileoverview|file|overview|module)\b\s*/u;
const TAG_LINE_PATTERN = /^@/u;
const WHITESPACE_RUN_PATTERN = /\s+/gu;
const SENTENCE_PATTERN = /[.!?](?=\s|$)/gu;
const ABBREVIATION_PATTERN = /(?:^|[\s([])(?:e\.g|i\.e|etc|vs|cf)\.$/u;
const EXPORT_PATTERN = new RegExp(
  '^export\\s+(?:(default)\\b|(?:async\\s+)?(?:function\\*?|class|const|let|var)' +
  '\\s+([\\w$]+)|\\{\\s*([\\w$]+)(?:\\s+as\\s+([\\w$]+))?)', 'mu');
const EXPORT_DEFAULT_GROUP = 1;
const EXPORT_DECLARATION_GROUP = 2;
const EXPORT_LIST_LOCAL_GROUP = 3;
const EXPORT_LIST_ALIAS_GROUP = 4;
const BLOCK_BODY_GROUP = 1;

// Non-ASCII characters folded to their ASCII spelling before any other
// fold (NFD would turn U+2260 into '=' plus a combining mark). A character
// not listed here is NFD-decomposed and its combining marks are stripped,
// so a Latin letter keeps its base letter; only what is still non-ASCII
// after that is dropped, so the generated markdown is ASCII.
const ASCII_FOLDS = Object.freeze({
  '\u2014': '-', '\u2013': '-', '\u2012': '-', '\u2011': '-', '\u2010': '-',
  '\u2212': '-', '\u2018': '\'', '\u2019': '\'', '\u201c': '"', '\u201d': '"',
  '\u2026': ELLIPSIS, '\u2192': '->', '\u2190': '<-', '\u2194': '<->',
  '\u21d2': '=>', '\u2264': '<=', '\u2265': '>=', '\u2260': '!=', '\u00d7': 'x',
  '\u00a0': SPACE, '\u00a7': 'S', '\u2248': '~', '\u00b7': '-', '\u2022': '-',
  '\u00df': 'ss', '\u00e6': 'ae', '\u00c6': 'AE', '\u00f8': 'o', '\u00d8': 'O',
  '\u0153': 'oe', '\u0152': 'OE', '\u0142': 'l', '\u0141': 'L', '\u0111': 'd',
  '\u0110': 'D',
});
const NON_ASCII_PATTERN = /[^\x20-\x7e]/gu;
const COMBINING_MARK_PATTERN = /[\u0300-\u036f]/gu;
const DECOMPOSED_FORM = 'NFD';

function toPosix(relativePath) {
  return relativePath.split(path.sep).join(POSIX_SEPARATOR);
}

function byCodePoint(left, right) {
  if (left === right) return 0;
  return left < right ? -1 : 1;
}

function foldCharacter(character) {
  const listed = ASCII_FOLDS[character];
  if (listed !== undefined) return listed;
  return character.normalize(DECOMPOSED_FORM)
    .replace(COMBINING_MARK_PATTERN, '')
    .replace(NON_ASCII_PATTERN, '');
}

function foldToAscii(text) {
  return text.replace(NON_ASCII_PATTERN, foldCharacter);
}

function collapse(text) {
  return text.replace(WHITESPACE_RUN_PATTERN, SPACE).trim();
}

function blockText(body) {
  const kept = [];
  for (const rawLine of body.split(NEWLINE)) {
    const trimmed = rawLine.replace(BLOCK_LINE_PREFIX_PATTERN, '').trim();
    if (FILE_TAG_PATTERN.test(trimmed)) {
      kept.push(trimmed.replace(FILE_TAG_PATTERN, ''));
    } else if (TAG_LINE_PATTERN.test(trimmed)) {
      break;
    } else {
      kept.push(trimmed);
    }
  }
  return collapse(kept.join(SPACE));
}

function lineCommentText(lines) {
  return collapse(lines.split(NEWLINE)
    .map((line) => line.replace(LINE_COMMENT_PREFIX_PATTERN, ''))
    .join(SPACE));
}

// The leading comments before any code, in order; a lint directive is
// skipped because it describes the linter, not the file.
function leadingCommentText(source) {
  let rest = source;
  for (;;) {
    const block = LEADING_BLOCK_PATTERN.exec(rest);
    const lines = block ? null : LEADING_LINES_PATTERN.exec(rest);
    const match = block ?? lines;
    if (!match) return '';
    const text = block ?
      blockText(match[BLOCK_BODY_GROUP]) :
      lineCommentText(match[BLOCK_BODY_GROUP]);
    rest = rest.slice(match[0].length);
    if (text !== '' && !DIRECTIVE_PATTERN.test(text)) return text;
  }
}

function firstJsdocText(source) {
  const match = JSDOC_PATTERN.exec(source);
  return match ? blockText(match[BLOCK_BODY_GROUP]) : '';
}

function firstSentence(text) {
  for (const match of text.matchAll(SENTENCE_PATTERN)) {
    const end = match.index + 1;
    if (match[0] === SENTENCE_END && ABBREVIATION_PATTERN.test(text.slice(0, end))) {
      continue;
    }
    return text.slice(0, end);
  }
  return text;
}

function cutAtWordBoundary(text) {
  if (text.length <= SUMMARY_LIMIT) return text;
  const head = text.slice(0, SUMMARY_LIMIT - ELLIPSIS.length);
  const boundary = head.lastIndexOf(SPACE);
  const kept = boundary > 0 ? head.slice(0, boundary) : head;
  return `${kept}${ELLIPSIS}`;
}

function firstExportName(source) {
  const match = EXPORT_PATTERN.exec(source);
  if (!match) return null;
  if (match[EXPORT_DEFAULT_GROUP]) return DEFAULT_EXPORT_NAME;
  return match[EXPORT_DECLARATION_GROUP] ??
    match[EXPORT_LIST_ALIAS_GROUP] ??
    match[EXPORT_LIST_LOCAL_GROUP];
}

/**
 * The one-sentence summary of a source file, from its comments only.
 * @param {string} source file text
 * @return {string} at most 120 ASCII characters
 */
export function summarizeSource(source) {
  const body = source.replace(SHEBANG_PATTERN, '');
  const comment = foldToAscii(leadingCommentText(body) || firstJsdocText(body));
  if (comment !== '') return cutAtWordBoundary(firstSentence(collapse(comment)));
  const exportName = firstExportName(body);
  return exportName === null ?
    NO_COMMENT_NO_EXPORT :
    cutAtWordBoundary(`${NO_COMMENT_PREFIX}${exportName}${SENTENCE_END}`);
}

/**
 * The band an importer count falls in.
 * @param {number} count files importing the file
 * @return {string} none, one, few, many or hub
 */
export function importerBand(count) {
  const band = IMPORTER_BANDS.find((candidate) => count <= candidate.atMost);
  return band ? band.label : HUB_BAND;
}

function listSourceDirectories(root, relativeDir) {
  const entries = fs.readdirSync(path.join(root, relativeDir), {withFileTypes: true});
  const directories = entries
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith(HIDDEN_PREFIX))
    .map((entry) => entry.name)
    .sort(byCodePoint);
  const files = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(JAVASCRIPT_SUFFIX))
    .map((entry) => entry.name)
    .sort(byCodePoint);
  const own = {relativeDir, directories, files};
  return [own, ...directories.flatMap((name) =>
    listSourceDirectories(root, toPosix(path.join(relativeDir, name))))];
}

function renderIndex(root, directory, importers) {
  const lines = [HEADER, '', `# ${directory.relativeDir}`, ''];
  if (directory.directories.length > 0) {
    lines.push(DIRECTORIES_HEADING, '');
    for (const name of directory.directories) {
      lines.push(`- [${name}](${name}/${INDEX_FILE})`);
    }
    lines.push('');
  }
  if (directory.files.length > 0) {
    lines.push(FILES_HEADING, '');
    for (const name of directory.files) {
      const relativePath = `${directory.relativeDir}${POSIX_SEPARATOR}${name}`;
      const source = fs.readFileSync(path.join(root, relativePath), UTF8);
      const band = importerBand((importers[relativePath] ?? []).length);
      lines.push(`- [${name}](${name}) - ${summarizeSource(source)} (importers: ${band})`);
    }
    lines.push('');
  }
  return lines.join(NEWLINE);
}

/**
 * Every index the generator would write, keyed by directory.
 * @param {string} root repository root
 * @return {{ok: true, indexes: Map<string, string>}|{ok: false, problem: string}}
 */
export function buildSourceOwnerIndexes(root) {
  const sealed = loadSealedImporters(root);
  if (!sealed.ok) return {ok: false, problem: sealed.problem};
  const indexes = new Map();
  for (const directory of listSourceDirectories(root, SOURCE_ROOT)) {
    indexes.set(directory.relativeDir, renderIndex(root, directory, sealed.importers));
  }
  return {ok: true, indexes};
}

function readIndex(absolutePath) {
  return fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, UTF8) : null;
}

function indexFindings(root, indexes) {
  const findings = [];
  for (const [relativeDir, expected] of indexes) {
    const relativePath = `${relativeDir}${POSIX_SEPARATOR}${INDEX_FILE}`;
    const actual = readIndex(path.join(root, relativePath));
    if (actual === null) findings.push(`${FINDING.MISSING} ${relativePath}`);
    else if (actual !== expected) findings.push(`${FINDING.STALE} ${relativePath}`);
  }
  return findings;
}

// Strict: only the known flags, each at most once; anything else is a
// refusal, never a silent fall back to --write.
function parseArguments(argv, defaultRoot) {
  const seen = new Set();
  let root = defaultRoot;
  for (let at = 0; at < argv.length; at += 1) {
    const argument = argv[at];
    if (seen.has(argument)) return {ok: false, problem: `repeated argument ${argument}`};
    seen.add(argument);
    if (argument === ROOT_FLAG) {
      const value = argv[at + 1];
      if (value === undefined || value.startsWith(FLAG_PREFIX)) {
        return {ok: false, problem: `${ROOT_FLAG} needs a directory`};
      }
      root = path.resolve(value);
      at += 1;
    } else if (argument !== WRITE_FLAG && argument !== CHECK_FLAG) {
      return {ok: false, problem: `unknown argument ${argument}`};
    }
  }
  if (seen.has(CHECK_FLAG) && seen.has(WRITE_FLAG)) {
    return {ok: false, problem: `${CHECK_FLAG} and ${WRITE_FLAG} are exclusive`};
  }
  return {ok: true, mode: seen.has(CHECK_FLAG) ? MODE.CHECK : MODE.WRITE, root};
}

/**
 * Runs the generator or its staleness audit.
 * @param {{root?: string, argv: string[], stdout: function(string): void,
 *   stderr: function(string): void}} options
 * @return {number} exit code
 */
export function runSourceOwnerIndex({root = REPO_ROOT, argv, stdout, stderr}) {
  const options = parseArguments(argv, root);
  if (!options.ok) {
    stderr(`source owner index refused: ${options.problem}; ${USAGE}`);
    return EXIT_FAILURE;
  }
  const built = buildSourceOwnerIndexes(options.root);
  if (!built.ok) {
    stderr(`source owner index refused: ${built.problem}; ${REFUSAL_HINT}`);
    return EXIT_FAILURE;
  }
  if (options.mode === MODE.CHECK) {
    const findings = indexFindings(options.root, built.indexes);
    for (const finding of findings) stdout(finding);
    stdout(String(findings.length));
    return findings.length > 0 ? EXIT_FAILURE : EXIT_SUCCESS;
  }
  for (const [relativeDir, content] of built.indexes) {
    fs.writeFileSync(path.join(options.root, relativeDir, INDEX_FILE), content);
  }
  stdout(`wrote ${built.indexes.size} source owner indexes`);
  return EXIT_SUCCESS;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = runSourceOwnerIndex({
    argv: process.argv.slice(ARGV_OFFSET),
    stdout: (line) => process.stdout.write(`${line}${NEWLINE}`),
    stderr: (line) => process.stderr.write(`${line}${NEWLINE}`),
  });
}
