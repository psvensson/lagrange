function fmtSec(value, digits = 2) {
  return typeof value === 'number' ? `${formatNum(value, digits)} s` : '-';
}

function buildPhaseSpeedRow(target, claimKey) {
  const cell = target.claims[claimKey];
  if (!cell) throw new Error(`${target.label}/${claimKey}: no admission cell`);
  const t = cell.metrics?.runs?.[0]?.timingsSec;
  if (!t) {
    return {
      status: cell.status,
      values: [target.label, '-', '-', '-', '-', '-', '-', '-', '-'],
    };
  }
  return {
    status: cell.status,
    values: [
      target.label,
      fmtSec(t.totalScenarioSec),
      fmtSec(t.clusterReadySec),
      fmtSec(t.semanticGateTotalSec),
      fmtSec(t.warmupSec),
      fmtSec(t.workloadDrainSec),
      fmtSec(t.postVerifySec),
      fmtSec(t.maxSingleTxnExecutionSec, 3),
      fmtSec(t.maxSingleRequestSec, 3),
    ],
  };
}

function buildPartSpeedRow(target, claimKey) {
  const cell = target.claims[claimKey];
  if (!cell) throw new Error(`${target.label}/${claimKey}: no admission cell`);
  const t = cell.metrics?.runs?.[0]?.timingsSec;
  const p = t?.partsSec;
  if (!t || !p) {
    return {
      status: cell.status,
      values: [target.label, '-', '-', '-', '-', '-', '-', '-', '-', '-', '-', '-'],
    };
  }
  return {
    status: cell.status,
    values: [
      target.label,
      fmtSec(p.loadAndCases1To2Sec),
      fmtSec(p.case3PaymentSec),
      fmtSec(p.case4OrderStatusSec),
      fmtSec(p.case5DeliverySec),
      fmtSec(p.case6StockLevelSec),
      fmtSec(p.case7FailureAtomicitySec),
      fmtSec(p.case8RetryableConflictSec),
      fmtSec(p.case9aDurabilityPreRestartSec),
      fmtSec(p.case9bDurabilityRestartReloadSec),
      fmtSec(t.warmupSec),
      fmtSec(t.workloadDrainSec),
    ],
  };
}

function buildMeasurementBreakdownTable(matrix, {heading, targetIds, claimKey}) {
  const targets = arrayMap(targetIds, (id) => arrayFind(matrix.targets, (t) => t.targetId === id));
  return [
    {
      heading: `${heading} - End-to-End & Phase Execution Speed (seconds)`,
      description: 'Wall-clock seconds taken by each system to complete the entire Scenario A ' +
        'journey and each major execution phase (lower is faster).',
      headers: PHASE_SPEED_HEADERS,
      rows: arrayMap(targets, (t) => buildPhaseSpeedRow(t, claimKey)),
    },
    {
      heading: `${heading} - Per-Part Scenario A Time Breakdown (seconds)`,
      description: 'Observed seconds taken by each system on each individual part of Scenario A ' +
        '(Parts 1-9 semantic workload cases, Part 10 warmup, and Part 11 measured workload).',
      headers: PART_SPEED_HEADERS,
      rows: arrayMap(targets, (t) => buildPartSpeedRow(t, claimKey)),
    },
  ];
}

function renderOneBreakdownTableMarkdown(table) {
  const header = `| ${arrayJoin(table.headers, ' | ')} |`;
  const rule = `| ${arrayJoin(arrayMap(table.headers, () => '---'), ' | ')} |`;
  const rows = arrayMap(table.rows, (r) =>
    `| ${arrayJoin(arrayMap(r.values, mdEscape), ' | ')} |`);
  return [`## ${table.heading}`, '', table.description, '', header, rule, ...rows, ''];
}

function renderBreakdownMarkdown(breakdown) {
  if (!breakdown) return [];
  const tables = Array.isArray(breakdown) ? breakdown : [breakdown];
  const out = [];
  for (const table of tables) out.push(...renderOneBreakdownTableMarkdown(table));
  return out;
}

function renderOneBreakdownTableHtml(table) {
  const head = arrayJoin(arrayMap(table.headers, (h) => `<th>${escapeXml(h)}</th>`), '');
  const rows = arrayMap(table.rows, (r) =>
    `<tr class="${escapeXml(r.status)}">` +
    arrayJoin(arrayMap(r.values, (v) => `<td>${escapeXml(v)}</td>`), '') + '</tr>');
  return `<h2>${escapeXml(table.heading)}</h2><p>${escapeXml(table.description)}</p>` +
    `<table><thead><tr>${head}</tr></thead><tbody>${arrayJoin(rows, '')}</tbody></table>`;
}

function renderBreakdownHtml(breakdown) {
  if (!breakdown) return '';
  const tables = Array.isArray(breakdown) ? breakdown : [breakdown];
  return arrayJoin(arrayMap(tables, renderOneBreakdownTableHtml), '');
}

function buildExperimentSection(matrix, experimentId, description) {
  const exp = arrayFind(matrix.experiments, (e) => e.experimentId === experimentId);
  return {
    heading: exp.title, description,
    columns: arrayMap(exp.columns, (c) => column(c)),
    rows: arrayMap(exp.rows, (r) => ({label: r.label, cells: r.cells})),
  };
}

function mdEscape(text) {
  return stringReplace(String(text), /\|/gu, '\\|');
}

function renderSectionMarkdown(section) {
  const header = `| Configuration | ${arrayJoin(arrayMap(section.columns, (c) => c.label), ' | ')} |`;
  const rule = `| --- | ${arrayJoin(arrayMap(section.columns, () => '---'), ' | ')} |`;
  const rows = arrayMap(section.rows, (row) => `| ${mdEscape(row.label)} | ${arrayJoin(
    arrayMap(section.columns, (c) => mdEscape(formatCell(row.cells[c.key]))), ' | ')} |`);
  return arrayJoin([`## ${section.heading}`, '', section.description, '', header, rule,
    ...rows, ''], '\n');
}

function renderStatusLegendMarkdown() {
  return arrayJoin(['## Cell status vocabulary', '',
    ...arrayMap(STATUS_MEANING, ([status, meaning]) => `- \`${status}\`: ${meaning}`), ''],
  '\n');
}

function renderSourcesMarkdown(sources) {
  return arrayJoin(['## Sources', '',
    ...arrayMap(sources, (s) => `- \`${s.path}\` ${s.sha256 ?? 'absent'}`), ''], '\n');
}

const WITHDRAWAL_LEAD = 'Every comparative result published before 2026-11-01 was withdrawn; ' +
  'the records are retained as forensic evidence.';

// The withdrawal notice states what the ledger and history hold (see
// summarizeBenchmarkWithdrawal); it asserts no universal. Public pages cite the
// ledger by entry and the admission rule by code, never development records.
function renderWithdrawalNotice(withdrawal, {ledger, code}) {
  if (!withdrawal) throw new Error('a claim page requires the withdrawal summary');
  const w = withdrawal;
  const entries = `${w.ledgerEntries} ${w.ledgerEntries === 1 ? 'entry' : 'entries'}`;
  return `${WITHDRAWAL_LEAD} The append-only ${ledger} has ${entries}; ` +
    `${w.entriesWithDefectIds} of them name the defect ids behind the withdrawal and ` +
    `${w.entriesWithRecordIds} of them enumerate the withdrawn records by id (the rest ` +
    'name them by file and campaign commit). ' +
    `${w.historyRecordsWithoutEntry} of ${w.historyRecords} history records are withdrawn ` +
    `without a ledger entry, by the admission rule ${code(w.admissionRule)}: no history ` +
    'record is admissible as a current claim.';
}

/**
 * Render a page as Markdown.
 * @param {{title: string, intro: Array<string>, sections: Array<Object>,
 *   links?: Array<{href: string, label: string}>, sources: Array<Object>,
 *   svgHref?: string}} page
 * @return {string}
 */
function renderClaimPageMarkdown(page) {
  const links = (page.links || []).length > 0 ?
    ['## Related pages', '', ...arrayMap(page.links, (l) => `- [${l.label}](${l.href})`), ''] :
    [];
  const svg = page.svgHref ? [`![${page.title}](${page.svgHref})`, ''] : [];
  const breakdown = renderBreakdownMarkdown(page.measurementBreakdown);
  return arrayJoin([`<!-- ${GENERATED_MARKER} -->`, '', `# ${page.title}`, '',
    ...arrayMap(page.intro, (p) => `${p}\n`),
    ...breakdown,
    ...arrayMap(page.sections, renderSectionMarkdown),
    ...svg,
    renderStatusLegendMarkdown(),
    renderWithdrawalNotice(page.withdrawal, {
      ledger: `[invalidation ledger](${LEDGER_HREF})`, code: (c) => `\`${c}\``,
    }), '',
    ...links,
    renderSourcesMarkdown(page.sources)], '\n');
}

function renderSectionHtml(section) {
  const head = arrayJoin(arrayMap(section.columns, (c) => `<th>${escapeXml(c.label)}</th>`), '');
  const rows = arrayMap(section.rows, (row) => `<tr><td>${escapeXml(row.label)}</td>` +
    arrayJoin(arrayMap(section.columns, (c) => {
      const cell = row.cells[c.key];
      if (!cell) throw new Error(`${row.label}/${c.key}: no admission cell`);
      return `<td class="${escapeXml(cell.status)}">` +
        `${escapeXml(formatCell(cell))}</td>`;
    }), '') + '</tr>');
  return `<h2>${escapeXml(section.heading)}</h2><p>${escapeXml(section.description)}</p>` +
    `<table><thead><tr><th>Configuration</th>${head}</tr></thead>` +
    `<tbody>${arrayJoin(rows, '')}</tbody></table>`;
}

function renderClaimPageHtml(page) {
  const links = arrayMap(page.links || [], (l) =>
    `<li><a href="${escapeXml(l.href)}">${escapeXml(l.label)}</a></li>`);
  const legend = arrayMap(STATUS_MEANING, ([status, meaning]) =>
    `<li><code>${escapeXml(status)}</code>: ${escapeXml(meaning)}</li>`);
  const sources = arrayMap(page.sources, (s) =>
    `<li><code>${escapeXml(s.path)}</code> ${escapeXml(s.sha256 ?? 'absent')}</li>`);
  return `<!DOCTYPE html>\n<!-- ${escapeXml(GENERATED_MARKER)} -->\n<html lang="en"><head>` +
    `<meta charset="utf-8"><title>${escapeXml(page.title)}</title><style>` +
    'body{font-family:sans-serif;max-width:1200px;margin:2rem auto;padding:0 1rem}' +
    'table{border-collapse:collapse;font-size:12px}td,th{border:1px solid #cbd5e1;' +
    'padding:4px;vertical-align:top}.invalid-measurement{color:#b91c1c}' +
    '.product-failure{color:#c2410c}.valid-observed{color:#15803d}.blocked{color:#6d28d9}' +
    '.unsupported{color:#475569}.not-measured{color:#64748b}</style></head><body>' +
    `<h1>${escapeXml(page.title)}</h1>` +
    arrayJoin(arrayMap(page.intro, (p) => `<p>${escapeXml(p)}</p>`), '') +
    renderBreakdownHtml(page.measurementBreakdown) +
    arrayJoin(arrayMap(page.sections, renderSectionHtml), '') +
    `<h2>Cell status vocabulary</h2><ul>${arrayJoin(legend, '')}</ul>` +
    `<p>${renderWithdrawalNotice(page.withdrawal, {
      ledger: `<a href="${LEDGER_HREF}">invalidation ledger</a>`,
      code: (c) => `<code>${escapeXml(c)}</code>`,
    })}</p>` +
    (links.length > 0 ? `<h2>Related pages</h2><ul>${arrayJoin(links, '')}</ul>` : '') +
    `<h2>Sources</h2><ul>${arrayJoin(sources, '')}</ul></body></html>\n`;
}

/**
 * Render every artifact of a page.
 * @param {Object} page
 * @return {{markdown: string, html: string, svg: string}}
 */
function renderClaimPage(page) {
  return {
    markdown: renderClaimPageMarkdown(page),
    html: renderClaimPageHtml(page),
    svg: renderStatusGridSvg(page),
  };
}

async function writeText(filePath, text) {
  await fs.mkdir(path.dirname(filePath), {recursive: true});
  await fs.writeFile(filePath, text, 'utf8');
}

/**
 * Write a page's artifacts. Any path may be omitted.
 * @param {Object} page
 * @param {{markdownPath?: string, htmlPath?: string, svgPath?: string}} paths
 * @return {Promise<Object>} The rendered artifacts.
 */
async function writeClaimPageArtifacts(page, paths) {
  const rendered = renderClaimPage(page);
  if (paths.markdownPath) await writeText(paths.markdownPath, rendered.markdown);
  if (paths.htmlPath) await writeText(paths.htmlPath, rendered.html);
  if (paths.svgPath) await writeText(paths.svgPath, rendered.svg);
  return rendered;
}

