// Markdown/HTML rendering of admission cells, and the page writer every
// comparative benchmark page uses. A cell prints its status word and reason codes;
// metrics appear only for valid-observed and product-failure cells, failure classes
// are printed separately (never summed), and a smoke or insufficient run prints
// counts only, never a capacity figure.
import fs from 'node:fs/promises';
import path from 'node:path';

import {CLAIM_CELL_STATUS} from './benchmark-claim-admission.js';
import {escapeXml, formatNum, renderStatusGridSvg} from './comparative-landing-svg-renderer.js';

const arrayFind = Function.call.bind(Array.prototype.find);
const arrayJoin = Function.call.bind(Array.prototype.join);
const arrayMap = Function.call.bind(Array.prototype.map);
const stringReplace = Function.call.bind(String.prototype.replace);

const GENERATED_MARKER = 'Generated by the comparative benchmark renderers from the raw ' +
  'observation store and the invalidation ledger; do not edit. ' +
  '`npm run audit:comparative-recompute` fails when this file differs from a regeneration.';
const LEDGER_HREF = '../../data/tidb-comparison/invalidations.ndjson';
// Public pages cite the withdrawal by invalidation entry id and defect id only;
// they never link development records.
const INVALIDATION_ENTRY_NOTE = 'each entry (inv-NNNN) names the withdrawn records, the ' +
  'admission reason codes and the defect ids (DNN) behind the withdrawal.';

const STATUS_MEANING = Object.freeze([
  [CLAIM_CELL_STATUS.VALID_OBSERVED, 'admitted from retained v2 observations'],
  [CLAIM_CELL_STATUS.PRODUCT_FAILURE, 'the product ran and failed; failure counts are shown'],
  [CLAIM_CELL_STATUS.INVALID_MEASUREMENT,
    'evidence exists but cannot support the claim (reason codes name why)'],
  [CLAIM_CELL_STATUS.BLOCKED, 'cannot be measured until a named prerequisite exists'],
  [CLAIM_CELL_STATUS.UNSUPPORTED, 'the configuration cannot express this claim'],
  [CLAIM_CELL_STATUS.NOT_MEASURED, 'no observation exists'],
]);

function formatAccounting(a) {
  const failures = arrayMap(Object.entries(a.terminalFailures),
    ([cls, n]) => `${cls} ${n}`);
  return `offered ${a.offered}, issued ${a.issued}, committed ${a.committed}, ` +
    `conflict-exhausted ${a.conflictExhausted}, ${arrayJoin(failures, ', ')}, ` +
    `unresolved ${a.unresolved}, unissued ${a.unissued}`;
}

function formatCapacity(metrics) {
  const rates = arrayMap(metrics.capacity.byRate, (r) =>
    `${formatNum(r.offeredRatePerSec, 1)}/s offered: committed/s min ` +
    `${formatNum(r.committedPerSec.min)} max ${formatNum(r.committedPerSec.max)} ` +
    `mean ${formatNum(r.committedPerSec.mean)} over ${r.repetitions} repetitions`);
  const p99 = arrayMap(metrics.runs, (m) => `${m.runId} p99 ${formatNum(m.latencyMs?.p99)} ms`);
  return `${arrayJoin(rates, '; ')}; ${arrayJoin(p99, '; ')}`;
}

/**
 * One cell as text: status word, reason codes, and for metric-bearing cells the
 * accounting (and capacity figures only when the sufficiency rule admitted them).
 * @param {Object|undefined} cell
 * @return {string}
 */
function formatCell(cell) {
  if (!cell) throw new Error('a rendered cell must come from admission; none was given');
  const reasons = cell.reasons.length > 0 ? ` (${arrayJoin(cell.reasons, ', ')})` : '';
  const head = `${cell.status}${reasons}`;
  if (!cell.metrics) return head;
  const setup = arrayMap(cell.metrics.setupFailures || [], (f) =>
    `; setup failed in ${f.runId}: ${f.failureClass}, sqlstate ${f.sqlState}, ` +
    `code ${f.code}, message ${f.message}`);
  const counts = `${cell.metrics.profileClass} profile: ` +
    `${formatAccounting(cell.metrics.accounting)}${arrayJoin(setup, '')}`;
  return cell.metrics.capacity ?
    `${head}: ${counts}; ${formatCapacity(cell.metrics)}` :
    `${head}: ${counts}`;
}

function column(key, label = key) {
  return {key, label};
}

function buildTargetSection(matrix, {heading, description, targetIds, columns}) {
  const targets = arrayMap(targetIds, (id) => arrayFind(matrix.targets, (t) => t.targetId === id));
  return {
    heading, description, columns,
    rows: arrayMap(targets, (t) => ({label: t.label, cells: t.claims})),
  };
}

function buildExperimentSection(matrix, experimentId, description) {
  const exp = arrayFind(matrix.experiments, (e) => e.experimentId === experimentId);
  return {
    heading: exp.title, description,
    columns: arrayMap(exp.columns, (c) => column(c)),
    rows: arrayMap(exp.rows, (r) => ({label: r.label, cells: r.cells})),
  };
}

function mdEscape(text) {
  return stringReplace(String(text), /\|/gu, '\\|');
}

function renderSectionMarkdown(section) {
  const header = `| Configuration | ${arrayJoin(arrayMap(section.columns, (c) => c.label), ' | ')} |`;
  const rule = `| --- | ${arrayJoin(arrayMap(section.columns, () => '---'), ' | ')} |`;
  const rows = arrayMap(section.rows, (row) => `| ${mdEscape(row.label)} | ${arrayJoin(
    arrayMap(section.columns, (c) => mdEscape(formatCell(row.cells[c.key]))), ' | ')} |`);
  return arrayJoin([`## ${section.heading}`, '', section.description, '', header, rule,
    ...rows, ''], '\n');
}

function renderStatusLegendMarkdown() {
  return arrayJoin(['## Cell status vocabulary', '',
    ...arrayMap(STATUS_MEANING, ([status, meaning]) => `- \`${status}\`: ${meaning}`), ''],
  '\n');
}

function renderSourcesMarkdown(sources) {
  return arrayJoin(['## Sources', '',
    ...arrayMap(sources, (s) => `- \`${s.path}\` ${s.sha256 ?? 'absent'}`), ''], '\n');
}

function renderWithdrawalNotice() {
  return 'Every comparative result published before 2026-11-01 was withdrawn: the records ' +
    'are retained as forensic evidence and the reasons are recorded in the append-only ' +
    `[invalidation ledger](${LEDGER_HREF}); ${INVALIDATION_ENTRY_NOTE}`;
}

/**
 * Render a page as Markdown.
 * @param {{title: string, intro: Array<string>, sections: Array<Object>,
 *   links?: Array<{href: string, label: string}>, sources: Array<Object>,
 *   svgHref?: string}} page
 * @return {string}
 */
function renderClaimPageMarkdown(page) {
  const links = (page.links || []).length > 0 ?
    ['## Related pages', '', ...arrayMap(page.links, (l) => `- [${l.label}](${l.href})`), ''] :
    [];
  const svg = page.svgHref ? [`![${page.title}](${page.svgHref})`, ''] : [];
  return arrayJoin([`<!-- ${GENERATED_MARKER} -->`, '', `# ${page.title}`, '',
    ...arrayMap(page.intro, (p) => `${p}\n`), renderWithdrawalNotice(), '', ...svg,
    renderStatusLegendMarkdown(), ...arrayMap(page.sections, renderSectionMarkdown), ...links,
    renderSourcesMarkdown(page.sources)], '\n');
}

function renderSectionHtml(section) {
  const head = arrayJoin(arrayMap(section.columns, (c) => `<th>${escapeXml(c.label)}</th>`), '');
  const rows = arrayMap(section.rows, (row) => `<tr><td>${escapeXml(row.label)}</td>` +
    arrayJoin(arrayMap(section.columns, (c) => {
      const cell = row.cells[c.key];
      if (!cell) throw new Error(`${row.label}/${c.key}: no admission cell`);
      return `<td class="${escapeXml(cell.status)}">` +
        `${escapeXml(formatCell(cell))}</td>`;
    }), '') + '</tr>');
  return `<h2>${escapeXml(section.heading)}</h2><p>${escapeXml(section.description)}</p>` +
    `<table><thead><tr><th>Configuration</th>${head}</tr></thead>` +
    `<tbody>${arrayJoin(rows, '')}</tbody></table>`;
}

function renderClaimPageHtml(page) {
  const links = arrayMap(page.links || [], (l) =>
    `<li><a href="${escapeXml(l.href)}">${escapeXml(l.label)}</a></li>`);
  const legend = arrayMap(STATUS_MEANING, ([status, meaning]) =>
    `<li><code>${escapeXml(status)}</code>: ${escapeXml(meaning)}</li>`);
  const sources = arrayMap(page.sources, (s) =>
    `<li><code>${escapeXml(s.path)}</code> ${escapeXml(s.sha256 ?? 'absent')}</li>`);
  return `<!DOCTYPE html>\n<!-- ${escapeXml(GENERATED_MARKER)} -->\n<html lang="en"><head>` +
    `<meta charset="utf-8"><title>${escapeXml(page.title)}</title><style>` +
    'body{font-family:sans-serif;max-width:1200px;margin:2rem auto;padding:0 1rem}' +
    'table{border-collapse:collapse;font-size:12px}td,th{border:1px solid #cbd5e1;' +
    'padding:4px;vertical-align:top}.invalid-measurement{color:#b91c1c}' +
    '.product-failure{color:#c2410c}.valid-observed{color:#15803d}.blocked{color:#6d28d9}' +
    '.unsupported{color:#475569}.not-measured{color:#64748b}</style></head><body>' +
    `<h1>${escapeXml(page.title)}</h1>` +
    arrayJoin(arrayMap(page.intro, (p) => `<p>${escapeXml(p)}</p>`), '') +
    '<p>Every comparative result published before 2026-11-01 was withdrawn; see the ' +
    `<a href="${LEDGER_HREF}">invalidation ledger</a>; ${escapeXml(INVALIDATION_ENTRY_NOTE)}</p>` +
    `<h2>Cell status vocabulary</h2><ul>${arrayJoin(legend, '')}</ul>` +
    arrayJoin(arrayMap(page.sections, renderSectionHtml), '') +
    (links.length > 0 ? `<h2>Related pages</h2><ul>${arrayJoin(links, '')}</ul>` : '') +
    `<h2>Sources</h2><ul>${arrayJoin(sources, '')}</ul></body></html>\n`;
}

/**
 * Render every artifact of a page.
 * @param {Object} page
 * @return {{markdown: string, html: string, svg: string}}
 */
function renderClaimPage(page) {
  return {
    markdown: renderClaimPageMarkdown(page),
    html: renderClaimPageHtml(page),
    svg: renderStatusGridSvg(page),
  };
}

async function writeText(filePath, text) {
  await fs.mkdir(path.dirname(filePath), {recursive: true});
  await fs.writeFile(filePath, text, 'utf8');
}

/**
 * Write a page's artifacts. Any path may be omitted.
 * @param {Object} page
 * @param {{markdownPath?: string, htmlPath?: string, svgPath?: string}} paths
 * @return {Promise<Object>} The rendered artifacts.
 */
async function writeClaimPageArtifacts(page, paths) {
  const rendered = renderClaimPage(page);
  if (paths.markdownPath) await writeText(paths.markdownPath, rendered.markdown);
  if (paths.htmlPath) await writeText(paths.htmlPath, rendered.html);
  if (paths.svgPath) await writeText(paths.svgPath, rendered.svg);
  return rendered;
}

export {
  buildExperimentSection,
  buildTargetSection,
  column,
  formatCell,
  renderClaimPage,
  writeClaimPageArtifacts,
};
