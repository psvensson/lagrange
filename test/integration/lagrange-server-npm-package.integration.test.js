import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtemp, readFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {basename, join} from 'node:path';
import {describe, it} from 'node:test';
import {unreachableSrcModules, unresolvedPackageImports} from '../../scripts/checks/push-gate-unused-files.js';

import {
  PACKAGE_NAME,
  buildAndVerifyNpmPackage,
  inspectTarball,
} from '../../scripts/release-npm-package.js';

const PACKAGE_TEST_TIMEOUT_MS = 180000;
const MAX_PACKAGE_BYTES = 8 * 1024 * 1024;
const MAX_UNPACKED_BYTES = 25 * 1024 * 1024;
const MAX_PACKAGE_ENTRIES = 2150;
const REQUIRED_PACKAGE_PATHS = Object.freeze([
  'CHANGELOG.md',
  'LICENSE',
  'README.md',
  'package.json',
  'src/admin/static/playback-viewer.html',
  'src/admin/static/test-run-dashboard.html',
  'src/cli/bin/lagrange-admin.js',
  'src/authoring/index.js',
  'src/threading/service-worker.js',
  'src/runtime/wasi-component-cell-worker.js',
  'src/runtime/wasi-component-derivation-worker.js',
  'src/query/distributed/coordinator-merge-process.js',
  'src/public-api.js',
  'src/sea-entry.js',
  'vendor/raft-rs-wasm/artifact-digest.json',
  'vendor/raft-rs-wasm/pkg/raft_wasm.js',
  'vendor/raft-rs-wasm/pkg/raft_wasm_bg.wasm',
  'wit/world.wit',
]);
const FORBIDDEN_PACKAGE_PREFIXES = Object.freeze([
  '.github/',
  'architecture/',
  'data/',
  'dist/',
  'docs/',
  'node_modules/',
  'scripts/',
  'solve/',
  'src/test-helpers/',
  'test/',
]);

async function assertPackedSourceReferences(packed, directory, exclusions) {
  execFileSync('tar', ['-xzf', packed.tarballPath, '-C', directory]);
  const omittedNames = new Set(exclusions.map((file) => basename(file)));
  const unresolved = [];
  for (const {path} of packed.files) {
    if (!path.startsWith('src/') || !path.endsWith('.js')) continue;
    const source = await readFile(join(directory, 'package', path), 'utf8');
    // Also covers path segments passed to fs, Piscina, Worker, or createRequire.
    for (const name of source.match(/[\w.-]+\.js\b/gu) || []) {
      assert.ok(!omittedNames.has(name), `${path} references omitted ${name}`);
    }
    unresolved.push(...unresolvedPackageImports(source, path));
  }
  // The cell imports generated bytes via a data URL. Componentize is a declared
  // npm dependency behind a const alias and service build exercises that load.
  // Service authoring imports the caller-supplied source URL.
  assert.deepEqual(unresolved.sort(), [
    'src/runtime/wasi-component-cell-worker.js: import(moduleUrl)',
    'src/service/service-component-build.js: import(COMPONENTIZE_SPECIFIER)',
    'src/service/service-source-contract.js: import(url)',
  ]);
}

describe('lagrange-server npm distribution', () => {
  it('packs one commit-bound artifact and proves installed public start/stop, API and CLIs', {
    timeout: PACKAGE_TEST_TIMEOUT_MS,
  }, async (t) => {
    const temporaryRoot = await mkdtemp(join(tmpdir(), 'lagrange-server-npm-'));
    t.after(async () => rm(temporaryRoot, {recursive: true, force: true}));

    const packed = await buildAndVerifyNpmPackage({
      outputDirectory: temporaryRoot,
    });
    t.diagnostic(`npm tarball ${packed.gitHead} ${packed.integrity} contains ${packed.entryCount} entries, ` +
      `${packed.size} packed bytes and ${packed.unpackedSize} unpacked bytes`);
    assert.equal(packed.name, PACKAGE_NAME);
    assert.ok(packed.size <= MAX_PACKAGE_BYTES);
    assert.ok(packed.unpackedSize <= MAX_UNPACKED_BYTES);
    assert.ok(packed.entryCount <= MAX_PACKAGE_ENTRIES);

    const packedPaths = new Set(packed.files.map(({path}) => path));
    for (const requiredPath of REQUIRED_PACKAGE_PATHS) {
      assert.ok(packedPaths.has(requiredPath), `missing ${requiredPath}`);
    }
    for (const packedPath of packedPaths) {
      assert.equal(
        FORBIDDEN_PACKAGE_PREFIXES.some(
          (prefix) => packedPath.startsWith(prefix),
        ),
        false,
        `development-only path leaked into npm package: ${packedPath}`,
      );
    }

    const candidate = await inspectTarball(packed.tarballPath);
    const unreachable = new Set(unreachableSrcModules());
    const exclusions = [];
    for (const rule of candidate.manifest.files) {
      if (rule.startsWith('!src/') && rule.endsWith('.js')) {
        const excluded = rule.slice(1);
        exclusions.push(excluded);
        assert.ok(unreachable.has(excluded), `production module excluded from package: ${excluded}`);
        assert.ok(!packedPaths.has(excluded), `excluded module present: ${excluded}`);
      }
    }
    await assertPackedSourceReferences(packed, temporaryRoot, exclusions);
    assert.equal(candidate.manifest.name, PACKAGE_NAME);
    assert.equal(candidate.manifest.version, packed.version);
    assert.equal(candidate.manifest.gitHead, packed.gitHead);
    assert.equal(candidate.integrity, packed.integrity);
  });

  it('resolves the harness playback-viewer copy source to the packaged ' +
    'runtime asset (single owner, no checked-in twin)',
  async () => {
    const {OUTPUT} = await import(
      '../distributed/harness/constants.js');
    const copySource = join(
      import.meta.dirname,
      '../distributed/harness',
      OUTPUT.PLAYBACK_VIEWER_SOURCE_RELATIVE,
    );
    const canonical = join(
      import.meta.dirname,
      '../../src/admin/static/playback-viewer.html',
    );
    const [sourceBytes, canonicalBytes] = await Promise.all([
      readFile(copySource),
      readFile(canonical),
    ]);
    assert.deepEqual(sourceBytes, canonicalBytes);
  });
});
