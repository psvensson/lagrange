// Every src directory carries a generated INDEX.md: one line per file with
// its leading-comment summary and its importer count from the sealed import
// graph. Hermetic: a mkdtemp root carries the source tree, the graph and the
// seal that binds it, so the counts come from the fixture graph and never
// from this repository's.

import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {test} from 'node:test';

import {
  buildSourceOwnerIndexes,
  importerBand,
  runSourceOwnerIndex,
  summarizeSource,
} from '../../scripts/generate-source-owner-index.js';
import {
  IMPORT_GRAPH_PATH,
  IMPORT_GRAPH_SEAL_PATH,
} from '../../scripts/checks/impact-proof-cone-constants.js';

const SCRIPT = 'scripts/generate-source-owner-index.js';
const DIGEST_LENGTH = 64;
const SEAL = Object.freeze({
  schemaVersion: 1,
  importGraphSchemaVersion: 'global-owner-debt-import-graph-v2',
  sourceDigest: 'a'.repeat(DIGEST_LENGTH),
  producerInputDigest: 'b'.repeat(DIGEST_LENGTH),
  resolverStateDigest: 'c'.repeat(DIGEST_LENGTH),
  snapshotDigest: 'd'.repeat(DIGEST_LENGTH),
});
const IMPORTERS = Object.freeze({
  'src/alpha.js': ['src/sub/gamma.js', 'test/alpha.test.js', 'scripts/x.js'],
  'src/sub/gamma.js': ['src/alpha.js'],
});
const GRAPH = Object.freeze({
  schemaVersion: SEAL.importGraphSchemaVersion,
  sourceDigest: SEAL.sourceDigest,
  producerInputDigest: SEAL.producerInputDigest,
  resolverStateDigest: SEAL.resolverStateDigest,
  snapshotDigest: SEAL.snapshotDigest,
  importers: IMPORTERS,
});
const LONG_SENTENCE = 'Delta owns the long description of a boundary whose ' +
  'summary is far longer than one hundred and twenty characters in total length.';
const SOURCES = Object.freeze({
  'src/alpha.js': '#!/usr/bin/env node\n/**\n * Alpha owns the first thing, e.g. ' +
    'a seam. Second sentence.\n * @param {string} x\n */\nexport function alpha() {}\n',
  'src/beta.js': '// Beta routes \u2014 the second thing.\n// It continues here.\n\n' +
    'export const beta = 1;\n',
  'src/sub/gamma.js': 'import {alpha} from \'../alpha.js\';\n\nexport class Gamma {}\n' +
    'export const other = alpha;\n',
  'src/sub/delta.js': `/** ${LONG_SENTENCE} */\nexport default 1;\n`,
  'src/sub/notes.txt': 'not javascript\n',
});
const HEADER = '---\ndocumentClass: generated\n---\n' +
  '<!-- GENERATED by scripts/generate-source-owner-index.js via ' +
  'npm run generate:source-owner-index. Do not hand-edit. -->\n';
const GOLDEN_ROOT = HEADER + '\n# src\n\n## Directories\n\n' +
  '- [sub](sub/INDEX.md)\n\n## Files\n\n' +
  '- [alpha.js](alpha.js) - Alpha owns the first thing, e.g. a seam. (importers: few)\n' +
  '- [beta.js](beta.js) - Beta routes - the second thing. (importers: none)\n';
const GOLDEN_SUB = HEADER + '\n# src/sub\n\n## Files\n\n' +
  '- [delta.js](delta.js) - Delta owns the long description of a boundary whose ' +
  'summary is far longer than one hundred and twenty characters in... (importers: none)\n' +
  '- [gamma.js](gamma.js) - No leading comment; first export: Gamma. (importers: one)\n';

function writeFile(root, relative, text) {
  const absolute = path.join(root, relative);
  fs.mkdirSync(path.dirname(absolute), {recursive: true});
  fs.writeFileSync(absolute, text);
}

function fixtureRoot() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'source-owner-index-'));
  for (const [relative, text] of Object.entries(SOURCES)) {
    writeFile(root, relative, text);
  }
  writeFile(root, IMPORT_GRAPH_PATH, `${JSON.stringify(GRAPH)}\n`);
  writeFile(root, IMPORT_GRAPH_SEAL_PATH, `${JSON.stringify(SEAL)}\n`);
  return root;
}

function run(root, argv) {
  const lines = [];
  const code = runSourceOwnerIndex({
    root, argv, stdout: (line) => lines.push(line), stderr: () => {},
  });
  return {code, lines};
}

test('generation is deterministic and matches the golden indexes', () => {
  const root = fixtureRoot();
  const first = buildSourceOwnerIndexes(root);
  assert.equal(first.ok, true);
  assert.deepEqual([...first.indexes.keys()], ['src', 'src/sub']);
  assert.equal(first.indexes.get('src'), GOLDEN_ROOT);
  assert.equal(first.indexes.get('src/sub'), GOLDEN_SUB);
  assert.deepEqual(buildSourceOwnerIndexes(root).indexes, first.indexes);
  assert.equal(run(root, ['--write']).code, 0);
  assert.equal(fs.readFileSync(path.join(root, 'src/INDEX.md'), 'utf8'), GOLDEN_ROOT);
  assert.equal(fs.readFileSync(path.join(root, 'src/sub/INDEX.md'), 'utf8'), GOLDEN_SUB);
});

test('the summary is the first sentence of the leading JSDoc block', () => {
  assert.equal(summarizeSource('/**\n * One. Two.\n * @return {x}\n */\n'), 'One.');
  assert.equal(summarizeSource('/** @fileoverview Owner of x. More. */\n'),
    'Owner of x.');
  assert.equal(summarizeSource('import x from \'y\';\n/**\n * Later doc. More.\n */\n' +
    'export function f() {}\n'), 'Later doc.',
  'with no leading comment the first JSDoc block in the file answers');
});

test('leading line comments answer when there is no JSDoc block', () => {
  assert.equal(summarizeSource('// Routes a and b\n// across lines. Then more.\n'),
    'Routes a and b across lines.');
  assert.equal(summarizeSource('/* eslint-disable no-x */\n// Real summary.\n'),
    'Real summary.', 'a lint directive is not a summary');
});

test('a file with no comment says so and names its first export, never invents one', () => {
  assert.equal(summarizeSource('export async function run() {}\nexport const x = 1;\n'),
    'No leading comment; first export: run.');
  assert.equal(summarizeSource('const a = 1;\nexport {a as b, c};\n'),
    'No leading comment; first export: b.');
  assert.equal(summarizeSource('export default class {}\n'),
    'No leading comment; first export: default.');
  assert.equal(summarizeSource('const a = 1;\n'),
    'No leading comment and no named export.');
});

test('a summary over 120 characters is cut at a word boundary', () => {
  const summary = summarizeSource(`/** ${LONG_SENTENCE} */\n`);
  assert.ok(summary.length <= 120, `${summary.length} characters`);
  assert.ok(summary.endsWith('characters in...'), summary);
  assert.ok(LONG_SENTENCE.startsWith(summary.slice(0, -3)));
  // Character 118 is a space and a longer word follows: a 120 bound keeps
  // 117 characters before the ellipsis and so cuts at the earlier space; a
  // 121 bound would keep that space and the word before it.
  const head = `${'a'.repeat(110)} bbbbbb`;
  const boundary = `${head} ${'c'.repeat(10)}.`;
  assert.equal(boundary[117], ' ');
  assert.equal(summarizeSource(`/** ${boundary} */\n`), `${'a'.repeat(110)}...`);
});

test('non-ASCII text is folded to ASCII, keeping the base letter', () => {
  assert.equal(summarizeSource('/** The fa\u00e7ade is na\u00efve about ' +
    '\u00c5ngstr\u00f6m \u2018units\u2019 \u2014 x \u2260 y, gro\u00df. */\n'),
  'The facade is naive about Angstrom \'units\' - x != y, gross.');
});

test('an abbreviation after an opening parenthesis does not end the sentence', () => {
  assert.equal(summarizeSource('/** Spends a bound (e.g. a lease) once it lapses. ' +
    'Second sentence. */\n'), 'Spends a bound (e.g. a lease) once it lapses.');
  assert.equal(summarizeSource('/** Keeps rows [i.e. leases], files etc. ' +
    'until done. More. */\n'), 'Keeps rows [i.e. leases], files etc. until done.');
});

test('the index shows an importer band, never the exact count', () => {
  const bands = [[0, 'none'], [1, 'one'], [2, 'few'], [5, 'few'], [6, 'many'],
    [20, 'many'], [21, 'hub'], [1611, 'hub']];
  for (const [count, band] of bands) assert.equal(importerBand(count), band, `${count}`);
  const root = fixtureRoot();
  run(root, ['--write']);
  const grown = {...GRAPH, importers: {...IMPORTERS,
    'src/alpha.js': [...IMPORTERS['src/alpha.js'], 'test/more.test.js']}};
  writeFile(root, IMPORT_GRAPH_PATH, `${JSON.stringify(grown)}\n`);
  assert.deepEqual(run(root, ['--check']).lines, ['0'],
    'a count that stays inside its band leaves the index current');
  assert.doesNotMatch(fs.readFileSync(path.join(root, 'src/INDEX.md'), 'utf8'),
    /importers: \d/u);
});

test('importer counts come from the sealed graph, never from the sources', () => {
  const root = fixtureRoot();
  const graph = {...GRAPH, importers: {...IMPORTERS, 'src/beta.js': ['a', 'b']}};
  writeFile(root, IMPORT_GRAPH_PATH, `${JSON.stringify(graph)}\n`);
  const built = buildSourceOwnerIndexes(root);
  assert.match(built.indexes.get('src'), /\[beta\.js\].*\(importers: few\)/u);
  writeFile(root, IMPORT_GRAPH_SEAL_PATH,
    `${JSON.stringify({...SEAL, snapshotDigest: 'e'.repeat(DIGEST_LENGTH)})}\n`);
  assert.equal(buildSourceOwnerIndexes(root).ok, false,
    'a graph the seal does not bind is refused');
  const refused = run(root, ['--check']);
  assert.equal(refused.code, 1);
  assert.deepEqual(refused.lines, [], 'no count is printed for an unmeasured tree');
});

test('--check reports missing and stale indexes and prints the count last', () => {
  const root = fixtureRoot();
  const before = run(root, ['--check']);
  assert.equal(before.code, 1);
  assert.deepEqual(before.lines,
    ['missing src/INDEX.md', 'missing src/sub/INDEX.md', '2']);
  assert.equal(fs.existsSync(path.join(root, 'src/INDEX.md')), false,
    '--check writes nothing');
  run(root, []);
  writeFile(root, 'src/sub/epsilon.js', '// Epsilon.\n');
  const stale = run(root, ['--check']);
  assert.equal(stale.code, 1);
  assert.deepEqual(stale.lines, ['stale src/sub/INDEX.md', '1']);
  fs.rmSync(path.join(root, 'src/INDEX.md'));
  assert.deepEqual(run(root, ['--check']).lines,
    ['missing src/INDEX.md', 'stale src/sub/INDEX.md', '2']);
  run(root, ['--write']);
  fs.appendFileSync(path.join(root, 'src/INDEX.md'), '\n');
  assert.deepEqual(run(root, ['--check']).lines, ['stale src/INDEX.md', '1'],
    'a trailing newline alone is a hand edit');
});

test('--check on a freshly generated tree prints 0 and exits 0', () => {
  const root = fixtureRoot();
  run(root, ['--write']);
  const fresh = spawnSync(process.execPath, [SCRIPT, '--check', '--root', root],
    {encoding: 'utf8'});
  assert.equal(fresh.status, 0, fresh.stderr);
  assert.equal(fresh.stdout.trim().split('\n').at(-1), '0');
  fs.appendFileSync(path.join(root, 'src/INDEX.md'), 'hand edit\n');
  const edited = spawnSync(process.execPath, [SCRIPT, '--check', '--root', root],
    {encoding: 'utf8'});
  assert.equal(edited.status, 1);
  assert.equal(edited.stdout.trim().split('\n').at(-1), '1');
});

function treeDigest(root) {
  const hash = crypto.createHash('sha256');
  for (const relative of fs.readdirSync(root, {recursive: true}).sort()) {
    const absolute = path.join(root, relative);
    hash.update(relative);
    if (fs.statSync(absolute).isFile()) hash.update(fs.readFileSync(absolute));
  }
  return hash.digest('hex');
}

test('an unknown argument or a bare --root is refused and writes nothing', () => {
  const root = fixtureRoot();
  run(root, ['--write']);
  fs.appendFileSync(path.join(root, 'src/INDEX.md'), 'hand edit\n');
  const before = treeDigest(root);
  const refusals = [
    [['--chekc', '--root', root], /unknown argument --chekc/u],
    [['--check', '--root'], /--root needs a directory/u],
  ];
  for (const [argv, named] of refusals) {
    const refused = spawnSync(process.execPath, [SCRIPT, ...argv], {encoding: 'utf8'});
    assert.equal(refused.status, 1, argv.join(' '));
    assert.match(refused.stderr, named);
    assert.match(refused.stderr, /usage: /u);
    assert.doesNotMatch(refused.stdout, /^\d+$/mu, 'a refusal prints no count');
    assert.equal(treeDigest(root), before, 'a refusal writes nothing');
  }
});
