// Generates the real-ownership lab job from the candidate's PRODUCTION path:
// the Lagrange deployer is run with --storage-root and a recording sshRun; the
// first command it sends (the storage preparation container for node 1) is
// captured per campaign id, and the deployer is stopped at its first
// `docker run -d`. Usage (from any directory):
//   node solve/quests/comparative-campaign-explicit-provisioning/evidence/gen-storage-owner-job.mjs \
//     <clean checkout at the candidate> > job.sh
// then submit job.sh as a lab shell job on a host holding postgres:17-alpine (lab jobs
// 2109704c, a pasted copy at 5f1ea624c, and 1795d38a, generated by this file at 7ecc336c9).
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const worktree = process.argv[2];
const head = execFileSync('git', ['-C', worktree, 'rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();
const dirty = execFileSync('git', ['-C', worktree, 'status', '--porcelain'], {encoding: 'utf8'});
if (dirty.trim()) throw new Error('worktree is not clean');
const deployerFile = path.join(worktree, 'test/distributed/harness/real-product-deployer-lagrange.js');
const {deployLagrangeCluster} = await import(deployerFile);
const ROOT = '__ROOT__';
const STOP = new Error('stop at the first container start');

async function preparationCommand(campaignId) {
  const sent = [];
  const sshRun = async (_host, _opts, command) => {
    if (/^docker run -d /u.test(command)) throw STOP;
    sent.push(command);
    return '\n__exit_code=0';
  };
  await deployLagrangeCluster({hosts: ['10.0.0.1', '10.0.0.2', '10.0.0.3'], clientIp: '10.0.0.9',
    sshRun, campaignId, sleep: async () => {},
    opts: {lagrangeImage: 'psvensson/lagrange@sha256:' + 'c'.repeat(64), storageRoot: ROOT,
      lagrangeImageContent: 'sha256:' + 'a'.repeat(64)}}).catch(() => null);
  if (sent.length === 0) throw new Error(`no storage command for ${campaignId}`);
  // The deployer appends execWithStatus's trailer; the job prints the status itself.
  return sent[0].replace(/; printf '\\n__exit_code=%s' "\$\?"$/u, '');
}

const cases = [['camp-absent', 'absent'], ['camp-root-empty', 'root-owned empty'],
  ['camp-root-data', 'root-owned NON-EMPTY (foreign)'], ['camp-own-data', '10001-owned non-empty']];
const lines = [
  `# Generated at job-build time from ${head} (real-product-deployer-lagrange.js sha256 ` +
    `${createHash('sha256').update(fs.readFileSync(deployerFile)).digest('hex')}) by`,
  '# gen-storage-owner-job.mjs: each command line below is what the deployer sends for node 1.',
  '# Expected: absent, root-owned empty, 10001-owned non-empty -> exit 0, 10001:10001;',
  '# root-owned non-empty -> exit 3 "foreign 0:0", left 0:0 with its file.',
  'set -u',
  'dk() { if timeout 20 docker info >/dev/null 2>&1; then docker "$@"; else sg docker -c "docker $(printf \'%q \' "$@")"; fi; }',
  `echo "candidate ${head}"`,
  'ROOT="$HOME/lagrange-storage-owner-probe-$$"',
  'mkdir -p "$ROOT"',
  'dk run --rm --pull=never --network none -v "$ROOT:/r" postgres:17-alpine sh -c \'' +
    'mkdir -p /r/camp-root-empty/lagrange-1 /r/camp-root-data/lagrange-1 /r/camp-own-data/lagrange-1 && ' +
    'echo foreign > /r/camp-root-data/lagrange-1/data && echo earlier > /r/camp-own-data/lagrange-1/data && ' +
    'chown -R 10001:10001 /r/camp-own-data/lagrange-1\'',
  'show() { dk run --rm --pull=never --network none -v "$ROOT:/r" postgres:17-alpine sh -c \'for d in /r/*/lagrange-1; do echo "$d $(stat -c %u:%g $d) [$(ls -A $d | tr "\\n" " ")]"; done\'; }',
  'echo "== before"; show',
];
for (const [campaignId, label] of cases) {
  const command = (await preparationCommand(campaignId)).replace(ROOT, '"$ROOT"')
    .replace(/^docker /u, 'dk ');
  lines.push(`echo "== ${campaignId} (${label})"`, `out=$(${command} 2>&1); echo "exit=$? out=$out"`);
}
lines.push('echo "== after"; show', 'echo "== cleanup"',
  'dk run --rm --pull=never --network none -v "$HOME:/h" postgres:17-alpine rm -rf "/h/$(basename "$ROOT")"',
  'ls -ld "$ROOT" 2>&1 || true');
process.stdout.write(`${lines.join('\n')}\n`);
